// =====================================================
// 29단계. 원본과 최적화 이미지 비교
// =====================================================
// viewer-image-wrap은 상세 이미지를 표시하는 영역입니다.
//
// 현재 showOriginal 상태에 따라
// 작은 이미지 또는 큰 이미지를 출력합니다.
//
// 작은 이미지
// → 400 × 267 요청 주소 사용
//
// 큰 이미지
// → 1200 × 800 요청 주소 사용
//
// compare-box에는 두 방식의 특징을 설명합니다.
//
// 최적화 이미지
// → 작은 해상도
// → 일반적으로 낮은 전송량
// → 빠른 로딩에 유리
//
// 원본 이미지
// → 큰 해상도
// → 더 많은 세부 표현
// → 일반적으로 높은 전송량
//
// 실제 용량과 로딩 속도는 이미지 포맷,
// 압축률, 브라우저 캐시 등에 따라 달라집니다.


// =====================================================
// 30단계. React 상태 변경과 전체 실행 흐름
// =====================================================
// 사용자가 자연 카테고리를 선택했다고 가정합니다.
//
// 자연 버튼 클릭
// → onClick 이벤트 발생
// → setCategory("nature") 실행
// → category 상태 변경
// → filteredImages 다시 계산
// → 산 풍경과 바다 풍경만 표시
//
// 이미지가 로드되면
// → onLoad 이벤트 발생
// → handleImageLoad 실행
// → loadedMap 상태 변경
// → Skeleton UI 제거
// → loaded 클래스 적용
//
// 사용자가 상세 보기 버튼을 클릭하면
// → openViewer(image) 실행
// → selectedImage에 이미지 저장
// → 상세 보기 모달 표시
// → 작은 썸네일 이미지 출력
//
// 원본 이미지 버튼 클릭
// → setShowOriginal(true) 실행
// → showOriginal 상태 변경
// → 큰 이미지 주소로 전환
//
// 닫기 버튼 클릭
// → closeViewer 실행
// → selectedImage를 null로 변경
// → 상세 보기 모달 닫힘


// =====================================================
// 최종 실행 결과
// =====================================================
// 1. 총 6개의 이미지 데이터를 준비합니다.
// 2. 전체, 자연, 도시, 테크 필터를 제공합니다.
// 3. 처음에는 전체 이미지 6개를 표시합니다.
// 4. 카테고리를 선택하면 해당 이미지만 표시합니다.
// 5. 선택된 필터 버튼에 active 클래스를 적용합니다.
// 6. 갤러리에는 작은 썸네일 이미지를 사용합니다.
// 7. loading="lazy"로 이미지 로딩을 지연할 수 있습니다.
// 8. 이미지 로딩 전에는 Skeleton UI를 표시합니다.
// 9. 이미지 로딩 완료 후 Skeleton UI를 제거합니다.
// 10. width와 height로 이미지 비율 정보를 제공합니다.
// 11. 상세 보기 버튼을 클릭하면 모달이 열립니다.
// 12. 모달을 열면 기본적으로 썸네일을 표시합니다.
// 13. 원본 이미지 버튼을 클릭하면 큰 이미지를 표시합니다.
// 14. 최적화 이미지 버튼으로 작은 이미지로 돌아갑니다.
// 15. 모달 배경 또는 닫기 버튼을 클릭하면 모달이 닫힙니다.
// 16. React 상태 변경에 따라 화면이 자동 업데이트됩니다.


// =====================================================
// 핵심 학습 내용
// =====================================================
// useState → 이미지 필터와 모달 상태 관리
// useMemo → 카테고리별 이미지 필터링 결과 재사용
// images → 이미지 데이터 배열
// category → 현재 선택된 카테고리
// setCategory → 카테고리 변경
// selectedImage → 상세 보기에서 선택한 이미지
// setSelectedImage → 선택 이미지 변경
// loadedMap → 이미지별 로딩 완료 여부 저장
// setLoadedMap → 이미지 로딩 상태 업데이트
// showOriginal → 원본 이미지 표시 여부
// setShowOriginal → 원본과 썸네일 전환
// filteredImages → 카테고리별 필터링 결과
// filter → 조건에 맞는 이미지 추출
// map → 이미지 카드 반복 출력
// handleImageLoad → 이미지 로딩 완료 처리
// openViewer → 이미지 상세 보기 열기
// closeViewer → 이미지 상세 보기 닫기
// onLoad → 이미지 로딩 완료 이벤트
// onClick → 필터, 상세 보기, 닫기 버튼 처리
// loading="lazy" → 브라우저의 이미지 지연 로딩
// width / height → 이미지 크기와 비율 정보 제공
// Skeleton UI → 이미지 로딩 중 자리 표시 화면
// 조건부 렌더링 → Skeleton과 모달 표시 여부 결정
// 삼항 연산자 → 원본 또는 썸네일 이미지 선택
// 전개 연산자(...) → 기존 상태 객체 복사
// 계산된 속성명 [id] → 이미지 ID를 객체 속성으로 사용
// active → 현재 선택된 필터나 이미지 방식 강조
// loaded → 이미지 로딩 완료 스타일 적용
// stopPropagation → 모달 내부 클릭 이벤트 전파 방지
// role="dialog" → 대화상자 의미 지정
// aria-modal → 모달 대화상자임을 표시
// alt → 이미지의 대체 텍스트 제공
// key → React가 이미지 카드 요소를 구분
// 컴포넌트 재렌더링 → 상태 변경에 따른 화면 업데이트


// =====================================================
// 가장 중요한 React 이미지 최적화 작동 원리
// =====================================================
// 이미지 데이터 6개 준비
// → 갤러리에 썸네일 사용
// → loading="lazy"로 필요할 때 이미지 로딩
// → 로딩 중 Skeleton UI 표시
// → 이미지 로딩 완료
// → onLoad 이벤트 발생
// → loadedMap에 완료 상태 저장
// → Skeleton UI 제거
// → 이미지 화면 표시
//
// 카테고리 선택
// → setCategory 실행
// → category 상태 변경
// → useMemo로 filteredImages 계산
// → 선택한 카테고리의 이미지만 표시
//
// 상세 보기 버튼 클릭
// → openViewer 실행
// → selectedImage 상태 변경
// → 상세 보기 모달 표시
// → 기본 썸네일 이미지 표시
//
// 원본 이미지 버튼 클릭
// → setShowOriginal(true)
// → 큰 이미지 주소로 변경
// → 원본 크기 이미지 요청 및 표시
//
// 닫기 버튼 클릭
// → closeViewer 실행
// → selectedImage를 null로 변경
// → 모달 화면 제거
//
// 핵심: 갤러리에서는 가벼운 썸네일을 사용하고,
// 브라우저의 Lazy Loading으로 이미지 요청을 분산하며,
// 로딩 중에는 Skeleton UI를 표시합니다.
//
// 사용자가 상세 보기를 요청했을 때만
// 큰 이미지를 불러올 수 있도록 구성하여
// 초기 이미지 다운로드 부담을 줄이는 방식입니다.
