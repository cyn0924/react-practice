 // =====================================================
 // 핵심 학습 내용
 // =====================================================
 // useState → 현재 선택된 이미지 인덱스 관리
 // currentIndex → 선택된 이미지 위치
 // setCurrentIndex → 현재 이미지 변경
 // images → 갤러리 이미지 주소 배열
 // openLightbox → 라이트박스 열기
 // closeLightbox → 라이트박스 닫기
 // prevImage → 이전 이미지 이동
 // nextImage → 다음 이미지 이동
 // images.length → 전체 이미지 개수
 // images.length - 1 → 마지막 이미지 인덱스
 // map → 이미지 갤러리 반복 출력
 // onClick → 이미지 선택 및 이동 버튼 이벤트 처리
 // stopPropagation → 내부 클릭 이벤트 전파 방지
 // 조건부 렌더링 → 선택된 이미지가 있을 때만 라이트박스 표시
 // 삼항 연산자 → 첫 이미지와 마지막 이미지 순환 처리
 // 배열 인덱스 접근 → images[currentIndex]
 // img src → 이미지 주소 연결
 // img alt → 이미지 대체 텍스트 제공
 // key → React가 반복 생성한 이미지 구분
 // overlay → 확대 이미지 배경 영역
 // lightbox → 확대 이미지 표시 영역
 // className → 갤러리 및 라이트박스 CSS 스타일 적용
 // 컴포넌트 재렌더링 → 상태 변경에 따른 이미지 업데이트


 // =====================================================
 // 가장 중요한 React 이미지 라이트박스 작동 원리
 // =====================================================
 // 사용자가 갤러리 썸네일 클릭
 // → onClick 이벤트 발생
 // → openLightbox(index) 실행
 // → setCurrentIndex로 상태 변경
 // → React 컴포넌트 재렌더링
 // → currentIndex !== null 조건 만족
 // → overlay와 lightbox 화면 표시
 // → images[currentIndex] 이미지 확대 출력
 //
 // 이전 또는 다음 버튼 클릭
 // → prevImage 또는 nextImage 실행
 // → currentIndex 변경
 // → 확대 이미지 자동 변경
 //
 // 바깥 배경 또는 닫기 버튼 클릭
 // → closeLightbox 실행
 // → currentIndex를 null로 변경
 // → 라이트박스 화면 제거
 //
 // 핵심: useState로 현재 선택된 이미지의 인덱스를 관리하고
 // 조건부 렌더링으로 라이트박스를 표시하며,
 // 이전·다음 버튼으로 이미지 배열을 순환하는 구조입니다.
 //
 // 참고: 이 예제에는 키보드 ESC 닫기, 방향키 이동,
 // 이미지 확대 애니메이션 기능은 포함되어 있지 않습니다.
 // 실제 서비스에서는 키보드 접근성과 포커스 관리도 고려합니다.
