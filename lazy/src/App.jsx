 // React Lazy Loading 전체 실행 흐름
 // =====================================================
 // 1. React와 Suspense, lazy, useState를 불러옵니다.
 // 2. React.lazy로 홈 페이지 컴포넌트를 정의합니다.
 // 3. React.lazy로 소개 페이지 컴포넌트를 정의합니다.
 // 4. React.lazy로 프로필 페이지 컴포넌트를 정의합니다.
 // 5. App 컴포넌트에서 현재 선택된 메뉴를 관리합니다.
 // 6. 처음에는 홈 페이지를 선택한 상태로 시작합니다.
 // 7. 사용자가 홈, 소개, 프로필 버튼을 클릭합니다.
 // 8. 클릭한 메뉴에 따라 activeTab 상태를 변경합니다.
 // 9. renderPage 함수로 표시할 컴포넌트를 결정합니다.
 // 10. Suspense가 컴포넌트의 로딩 상태를 처리합니다.
 // 11. 로딩 중에는 fallback 화면을 표시할 수 있습니다.
 // 12. 컴포넌트가 준비되면 해당 페이지를 표시합니다.
 // 13. 선택한 메뉴 버튼에 active 클래스를 적용합니다.
 // 14. 다른 메뉴를 클릭하면 해당 화면으로 전환합니다.
 // 15. React 상태 변경에 따라 화면이 자동 업데이트됩니다.
 // =====================================================


 // =====================================================
 // 1단계. React 기능 및 CSS 불러오기
 // =====================================================
 // React는 컴포넌트를 만들기 위해 사용합니다.
 // lazy는 컴포넌트가 필요할 때 로드하도록 정의합니다.
 // Suspense는 로딩 중 표시할 대체 화면을 설정합니다.
 // useState는 현재 선택된 메뉴 상태를 관리합니다.
 // App.css는 메뉴, 카드, 로딩 화면의 디자인을 담당합니다.


 // =====================================================
 // 2단계. Lazy Loading이란?
 // =====================================================
 // Lazy Loading은 필요한 시점에 데이터를 불러오는 방식입니다.
 //
 // 일반적인 컴포넌트 로딩
 // → 여러 컴포넌트를 처음부터 불러옵니다.
 //
 // 지연 로딩
 // → 당장 필요하지 않은 컴포넌트의 로딩을 미룹니다.
 // → 해당 컴포넌트를 렌더링할 때 로딩을 시작합니다.
 //
 // 실제 프로젝트에서는 import()를 함께 사용하여
 // 파일 단위로 JavaScript 코드를 분리할 수 있습니다.
 //
 // 이를 통해 초기 다운로드 부담을 줄일 수 있습니다.


 // =====================================================
 // 3단계. React.lazy의 역할
 // =====================================================
 // React.lazy는 컴포넌트를 지연 로딩하도록 정의합니다.
 //
 // lazy는 Promise를 반환하는 함수를 전달받습니다.
 //
 // Promise의 결과에는 default 속성이 필요합니다.
 // default에는 렌더링할 React 컴포넌트가 들어갑니다.
 //
 // 실제 프로젝트에서는 다음과 같은 방식을 사용합니다.
 //
 // const HomePage = lazy(() => import("./pages/HomePage"));
 //
 // 현재 예제에서는 Promise.resolve()를 사용합니다.
 // 따라서 실제 별도 파일 다운로드는 발생하지 않습니다.


 // =====================================================
 // 4단계. Promise.resolve의 역할
 // =====================================================
 // Promise.resolve()는 주어진 값을
 // 이행된 Promise 형태로 반환합니다.
 //
 // 현재 예제에서는 컴포넌트를 default 속성에 담아 반환합니다.
 //
 // 예시
 // Promise.resolve({
 //   default: function HomePage() {
 //     ...
 //   }
 // })
 //
 // React.lazy가 이 Promise를 이용해
 // 렌더링할 컴포넌트를 가져오는 구조입니다.
 //
 // 하지만 컴포넌트 코드가 현재 파일에 있으므로
 // 실제 파일 단위 코드 분할은 구현되지 않습니다.


 // =====================================================
 // 5단계. HomePage 컴포넌트 정의
 // =====================================================
 // HomePage는 홈 메뉴를 선택했을 때 표시할 화면입니다.
 //
 // React.lazy를 이용하여 컴포넌트를 정의합니다.
 //
 // 화면 구성
 // 홈 페이지 제목
 // Lazy Loading 설명
 // 빠른 초기 렌더링 카드
 // 코드 분할 카드
 //
 // 처음 실행하면 홈 페이지가 선택됩니다.


 // =====================================================
 // 6단계. 홈 페이지의 핵심 내용
 // =====================================================
 // 홈 페이지에서는 Lazy Loading의 장점을 설명합니다.
 //
 // 첫 번째 카드
 // 빠른 초기 렌더링
 //
 // 필요한 컴포넌트만 불러오는 방식으로
 // 초기 화면의 로딩 부담을 줄일 수 있습니다.
 //
 // 두 번째 카드
 // 코드 분할
 //
 // 큰 프로젝트에서 컴포넌트를
 // 페이지 단위나 기능 단위로 나누어 관리할 수 있습니다.
 //
 // 실제 성능 효과는 코드 분할 방식과 사용 환경에 따라 달라집니다.


 // =====================================================
 // 7단계. AboutPage 컴포넌트 정의
 // =====================================================
 // AboutPage는 소개 메뉴를 선택했을 때 표시할 화면입니다.
 //
 // React.lazy를 이용하여 정의합니다.
 //
 // 화면 구성
 // 소개 페이지 제목
 // React.lazy와 Suspense 설명
 // 주요 학습 내용 목록
