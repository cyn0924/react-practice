// React.lazy → 지연 로딩할 컴포넌트 정의
// Suspense → 로딩 중 대체 화면 설정
// fallback → 컴포넌트가 준비되기 전 표시할 UI
// Promise.resolve → 이행된 Promise 생성
// default → lazy에서 렌더링할 컴포넌트 지정
// import() → JavaScript 모듈을 동적으로 불러오기
// Code Splitting → JavaScript 코드를 여러 청크로 분리
// Lazy Loading → 필요한 시점에 컴포넌트 로딩
// useState → 현재 선택된 페이지 상태 관리
// activePage → 현재 선택된 메뉴 이름
// setActivePage → 선택된 페이지 변경
// renderPage → 현재 메뉴에 맞는 컴포넌트 반환
// onClick → 메뉴 버튼 클릭 이벤트 처리
// 조건부 렌더링 → 선택된 페이지 컴포넌트 결정
// className → 메뉴 버튼 CSS 스타일 적용
// active → 현재 선택된 메뉴 강조
// 삼항 연산자 → active 클래스 적용 여부 결정
// style → 막대그래프의 높이 직접 지정
// page-content → 각 페이지 콘텐츠 영역
// content-card → 선택한 페이지를 표시하는 영역
// spinner → 로딩 상태를 표현하는 UI 요소
// 컴포넌트 재렌더링 → 상태 변경에 따른 화면 업데이트


