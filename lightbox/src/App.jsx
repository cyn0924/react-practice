// React 라이브러리와 상태 관리를 위한 useState Hook을 불러옵니다.
// useState는 현재 선택된 이미지 번호처럼 변경되는 값을 저장할 때 사용합니다.
import React, { useState } from "react";
import "./App.css";

// 이미지 갤러리와 라이트박스 기능을 담당하는 App 컴포넌트를 선언합니다.
function App() {

  // 갤러리에 표시할 이미지 주소를 배열로 저장합니다.
  // 배열 안의 이미지 순서가 화면에 표시되는 순서가 됩니다.
  const images = [
    "https://picsum.photos/id/1015/1200/800",
    "https://picsum.photos/id/1016/1200/800",
    "https://picsum.photos/id/1018/1200/800",
    "https://picsum.photos/id/1020/1200/800",
    "https://picsum.photos/id/1024/1200/800",
    "https://picsum.photos/id/1035/1200/800",
  ];

  // 현재 라이트박스에서 크게 보고 있는 이미지의 배열 위치를 저장합니다.
  // 아무 이미지도 선택하지 않은 처음 상태이므로 null로 시작합니다.
  const [currentIndex, setCurrentIndex] = useState(null);

  // 썸네일 이미지를 클릭했을 때 실행되는 함수입니다. 
  const openLightbox = (index) => {

    // 클릭한 이미지의 index를 저장합니다.
    setCurrentIndex(index);
  };

  // 라이트박스를 닫을 때 실행되는 함수입니다.
  const closeLightbox = (index) => {

    // currentIndex를 null로 변경합니다.
    // 조건부 렌더링에 의해 라이트박스가 화면에서 사라집니다.
    setCurrentIndex(null);
  };

  // 라이트박스에서 이전 이미지 버튼을 클릭했을 때 실행됩니다.
  const prevImage = () => {

    // 현재 index를 기준으로 이전 이미지의 index를 계산합니다.
    // 현재 이미지가 첫번째 이미지라면 마지막 이미지로 이동합니다.
    setCurrentIndex((prev) => prev === 0 ? images.length - 1 : prev - 1);
  };

  // 라이트박스에서 다음 이미지 버튼을 클릭했을 때 실행됩니다.
  const nextImage = () => {

    // 현재 index를 기준으로 다음 이미지의 index를 계산합니다.
    // 현재 이미지가 마지막 이미지라면 첫번째 이미지로 이동합니다.
    setCurrentIndex((prev) => prev === images.length - 1 ? 0 : prev + 1);
  };

  // 화면에 렌더링할 jsx를 불러옵니다.
  return (

    // 이미지 갤러리 전체를 감싸는 최상위 페이지 영역입니다.
    <div className="page">

      {/* 제목 */}
      <h1 className="title">이미지 라이트박스</h1>

      {/* 여러 개의 썸네일 이미지를 배치하는 갤러리 영역입니다. */}
      <div className="gallery">

        {/* images 배열의 이미지 개수만큼 img 요소를 반복해서 생성합니다. */}
        {images.map((img, index) => (

          // 반복해서 생성되는 요소를 구분하기 위해 index를 key로 사용합니다.
          <img 
            key={index}

            // 현재 반복 중인 이미지 주소를 src 속성에 연결합니다.
            src={img}

            // 이미지가 표시되지 않을 때 사용할 대체 텍스트입니다.
            alt={`gallery-${index}`}

            // css 클래스
            className="thumb"

            // 이미지를 클릭하면 클릭한 이미지의 index를 openLightbox 함수에 전달합니다.
            onClick={() => openLightbox(index)} 
          />
        ))}
      </div>

      {/* currentIndex가 null이 아닐 때만 라이트박스를 화면에 표시합니다. */}
      {currentIndex !== null && (

        // 화면 전체를 어둡게 덮는 반투명 오버레이 영역입니다.
        <div className="overlay" onClick={closeLightbox}>

          {/* 라이트 박스 내부를 클릭했을 때 오버레이의 닫기 이벤트가 실행되지 않도록 막습니다. */}
          <div className="lightbox" onClick={(e) => e.stopPropagation()}>
            
            {/* 현재 선택된 이미지의 큰 버전을 화면에 표시합니다. */}
            <img 
              src={image[currentIndex]}

              // 라이트박스 이미지에 대한 대체 텍스트입니다.
              alt="lightbox"

              // css 클래스
              className="image"
            />

            {/* 이전 이미지로 이동하는 버튼입니다. */}
            <button className="btn left" onClick={prevImage}>◀</button>

            {/* 다음 이미지로 이동하는 버튼입니다. */}
            <button className="btn right" onClick={nextImage}>▶</button>

            {/* 라이트 박스를 닫는 버튼입니다. */}
            <button className="close" onClick={closeLightbox}>✕</button>
          </div>
        </div>
      )}
    </div>
  )
};

export default App;

// =====================================================
 // React 이미지 라이트박스 전체 실행 흐름
 // =====================================================
 // 1. React와 useState를 불러옵니다.
 // 2. 갤러리에 사용할 이미지 6개를 준비합니다.
 // 3. 현재 선택된 이미지의 인덱스를 상태로 관리합니다.
 // 4. 처음에는 라이트박스가 닫힌 상태로 시작합니다.
 // 5. 이미지 배열을 반복하여 갤러리 썸네일을 출력합니다.
 // 6. 사용자가 썸네일 이미지를 클릭합니다.
 // 7. 클릭한 이미지의 인덱스를 currentIndex에 저장합니다.
 // 8. 라이트박스 배경과 확대 이미지를 화면에 표시합니다.
 // 9. 이전 버튼을 클릭하면 이전 이미지로 이동합니다.
 // 10. 다음 버튼을 클릭하면 다음 이미지로 이동합니다.
 // 11. 첫 이미지에서 이전을 누르면 마지막 이미지로 이동합니다.
 // 12. 마지막 이미지에서 다음을 누르면 첫 이미지로 이동합니다.
 // 13. 닫기 버튼이나 바깥 배경을 클릭하면 라이트박스를 닫습니다.
 // 14. 확대 이미지 내부를 클릭해도 라이트박스는 닫히지 않습니다.
 // 15. React 상태 변경에 따라 이미지가 자동 업데이트됩니다.
 // =====================================================


 // =====================================================
 // 1단계. React 기능 및 CSS 불러오기
 // =====================================================
 // React는 컴포넌트를 생성하기 위해 사용합니다.
 // useState는 현재 선택된 이미지의 인덱스를 관리합니다.
 // App.css는 갤러리, 확대 이미지, 버튼 디자인을 담당합니다.


 // =====================================================
 // 2단계. App 컴포넌트 생성
 // =====================================================
 // App은 이미지 갤러리와 라이트박스 전체를 관리합니다.
 //
 // 주요 역할
 // 이미지 목록 관리
 // 현재 선택된 이미지 관리
 // 라이트박스 열기
 // 라이트박스 닫기
 // 이전 이미지 이동
 // 다음 이미지 이동
 // 갤러리 썸네일 출력
 // 확대 이미지 표시
 //
 // 하나의 상태값으로 라이트박스의 동작을 제어합니다.


 // =====================================================
 // 3단계. 갤러리 이미지 데이터 준비
 // =====================================================
 // images 배열에 총 6개의 이미지 주소를 저장합니다.
 //
 // 각 이미지 주소는 Picsum Photos 서비스를 사용합니다.
 //
 // 이미지 배열의 인덱스는 0부터 시작합니다.
 //
 // 첫 번째 이미지 → images[0]
 // 두 번째 이미지 → images[1]
 // 세 번째 이미지 → images[2]
 // 네 번째 이미지 → images[3]
 // 다섯 번째 이미지 → images[4]
 // 여섯 번째 이미지 → images[5]
 //
 // 배열에 이미지를 추가하면 갤러리에도 자동으로 표시됩니다.


 // =====================================================
 // 4단계. 현재 선택된 이미지 상태 관리
 // =====================================================
 // currentIndex는 현재 선택한 이미지의 인덱스를 저장합니다.
 //
 // useState(null)로 초기값을 설정합니다.
 //
 // null이면 선택된 이미지가 없다는 뜻입니다.
 // 따라서 처음에는 라이트박스가 닫혀 있습니다.
 //
 // currentIndex = 0 → 첫 번째 이미지
 // currentIndex = 1 → 두 번째 이미지
 // currentIndex = 5 → 여섯 번째 이미지
 //
 // 인덱스가 변경되면 확대 이미지도 변경됩니다.


 // =====================================================
 // 5단계. 라이트박스 열기 함수 구현
 // =====================================================
 // openLightbox 함수는 썸네일 이미지를 클릭하면 실행됩니다.
 //
 // 클릭한 이미지의 index를 전달받습니다.
 //
 // 실행 흐름
 // 썸네일 클릭
 // → openLightbox(index) 실행
 // → setCurrentIndex(index) 실행
 // → currentIndex 상태 변경
 // → React 컴포넌트 재렌더링
 // → 라이트박스 화면 표시
 //
 // 클릭한 이미지가 확대된 상태로 나타납니다.


 // =====================================================
 // 6단계. 라이트박스 닫기 함수 구현
 // =====================================================
 // closeLightbox 함수는 확대 이미지 화면을 닫습니다.
 //
 // setCurrentIndex(null)을 실행합니다.
 //
 // 실행 흐름
 // 닫기 버튼 또는 바깥 배경 클릭
 // → closeLightbox 함수 실행
 // → currentIndex를 null로 변경
 // → React 컴포넌트 재렌더링
 // → 라이트박스 화면 제거
 //
 // 라이트박스를 닫아도 갤러리는 그대로 유지됩니다.


 // =====================================================
 // 7단계. 이전 이미지 이동 함수 구현
 // =====================================================
 // prevImage 함수는 이전 버튼을 클릭하면 실행됩니다.
 //
 // 실행 흐름
 // 이전 버튼 클릭
 // → prevImage 함수 실행
 // → 현재 이미지 인덱스 확인
 // → 인덱스를 1 감소
 // → setCurrentIndex 실행
 // → 이전 이미지로 변경
 //
 // 예시
 // 세 번째 이미지 → 이전 클릭 → 두 번째 이미지
 // 두 번째 이미지 → 이전 클릭 → 첫 번째 이미지


 // =====================================================
 // 8단계. 첫 번째 이미지에서 이전 버튼 클릭 처리
 // =====================================================
 // currentIndex가 0인지 확인합니다.
 //
 // 현재 첫 번째 이미지이면 마지막 인덱스로 이동합니다.
 //
 // images.length - 1로 마지막 이미지의 인덱스를 계산합니다.
 //
 // 이미지가 6개이므로 마지막 인덱스는 5입니다.
 //
 // 예시
 // 첫 번째 이미지 → 이전 클릭 → 여섯 번째 이미지
 //
 // 이를 통해 이미지가 순환하는 구조를 구현합니다.


 // =====================================================
 // 9단계. 다음 이미지 이동 함수 구현
 // =====================================================
 // nextImage 함수는 다음 버튼을 클릭하면 실행됩니다.
 //
 // 실행 흐름
 // 다음 버튼 클릭
 // → nextImage 함수 실행
 // → 현재 이미지 인덱스 확인
 // → 인덱스를 1 증가
 // → setCurrentIndex 실행
 // → 다음 이미지로 변경
 //
 // 예시
 // 첫 번째 이미지 → 다음 클릭 → 두 번째 이미지
 // 두 번째 이미지 → 다음 클릭 → 세 번째 이미지


 // =====================================================
 // 10단계. 마지막 이미지에서 다음 버튼 클릭 처리
 // =====================================================
 // currentIndex가 images.length - 1인지 확인합니다.
 //
 // 마지막 이미지라면 인덱스를 0으로 변경합니다.
 //
 // 예시
 // 여섯 번째 이미지 → 다음 클릭 → 첫 번째 이미지
 //
 // 마지막 이미지에서 멈추지 않고 다시 처음으로 돌아갑니다.
 //
 // 삼항 연산자를 이용하여 순환 이동을 처리합니다.


 // =====================================================
 // 11단계. JSX 전체 화면 구성
 // =====================================================
 // return에서 사용자가 보는 이미지 갤러리를 만듭니다.
 //
 // 화면 구성
 // 1. 이미지 라이트박스 제목
 // 2. 이미지 썸네일 갤러리
 // 3. 라이트박스 배경
 // 4. 확대 이미지
 // 5. 이전 이미지 버튼
 // 6. 다음 이미지 버튼
 // 7. 닫기 버튼
 //
 // 라이트박스는 이미지가 선택된 경우에만 표시됩니다.


 // =====================================================
 // 12단계. 이미지 갤러리 영역 구성
 // =====================================================
 // gallery는 전체 썸네일 이미지를 감싸는 영역입니다.
 //
 // images 배열을 map으로 반복하여 img 요소를 생성합니다.
 //
 // 이미지가 6개이므로 썸네일도 6개가 생성됩니다.
 //
 // 각 이미지에는 다음 속성을 적용합니다.
 // key → React가 이미지를 구분
 // src → 이미지 주소
 // alt → 이미지 대체 텍스트
 // className → 썸네일 CSS 스타일
 // onClick → 이미지 클릭 이벤트
 //
 // 이미지 배열의 순서대로 화면에 표시됩니다.


 // =====================================================
 // 13단계. 썸네일 이미지 클릭 처리
 // =====================================================
 // 사용자가 갤러리 이미지를 클릭하면 onClick이 실행됩니다.
 //
 // openLightbox(index)로 클릭한 이미지 위치를 전달합니다.
 //
 // 예시
 // 첫 번째 썸네일 클릭 → currentIndex = 0
 // 세 번째 썸네일 클릭 → currentIndex = 2
 // 여섯 번째 썸네일 클릭 → currentIndex = 5
 //
 // 선택된 이미지가 라이트박스에서 확대 표시됩니다.


 // =====================================================
 // 14단계. 라이트박스 조건부 렌더링
 // =====================================================
 // currentIndex !== null 조건을 확인합니다.
 //
 // currentIndex가 null이면 라이트박스를 표시하지 않습니다.
 //
 // currentIndex에 숫자가 저장되어 있으면
 // overlay와 lightbox 영역을 화면에 표시합니다.
 //
 // 조건부 렌더링에 && 연산자를 사용합니다.
 //
 // 이미지 선택 여부에 따라 라이트박스가 열리거나 닫힙니다.


 // =====================================================
 // 15단계. 라이트박스 배경 영역 구현
 // =====================================================
 // overlay는 확대 이미지 뒤에 표시되는 배경입니다.
 //
 // 사용자가 바깥 배경을 클릭하면 closeLightbox가 실행됩니다.
 //
 // 실행 흐름
 // 라이트박스 바깥 배경 클릭
 // → onClick 이벤트 발생
 // → closeLightbox 함수 실행
 // → currentIndex를 null로 변경
 // → 라이트박스 닫힘
 //
 // CSS에서 어두운 반투명 배경 등을 적용할 수 있습니다.


 // =====================================================
 // 16단계. 라이트박스 내부 클릭 이벤트 처리
 // =====================================================
 // lightbox는 실제 확대 이미지가 표시되는 영역입니다.
 //
 // e.stopPropagation()을 사용하여
 // 클릭 이벤트가 바깥 overlay로 전달되지 않도록 합니다.
 //
 // 확대 이미지나 내부 버튼을 클릭해도
 // 바깥 배경의 onClick 이벤트는 실행되지 않습니다.
 //
 // 따라서 이미지 내부를 클릭했을 때
 // 라이트박스가 의도치 않게 닫히는 것을 방지합니다.


 // =====================================================
 // 17단계. 확대 이미지 표시
 // =====================================================
 // images[currentIndex]로 현재 선택된 이미지를 가져옵니다.
 //
 // img의 src에 현재 이미지 주소를 연결합니다.
 //
 // 예시
 // currentIndex = 0 → 첫 번째 이미지 확대
 // currentIndex = 3 → 네 번째 이미지 확대
 // currentIndex = 5 → 여섯 번째 이미지 확대
 //
 // 이전 또는 다음 버튼을 클릭하면
 // currentIndex가 변경되어 이미지도 자동으로 변경됩니다.


 // =====================================================
 // 18단계. 이전 및 다음 이미지 버튼 구현
 // =====================================================
 // 라이트박스 내부에 두 개의 이동 버튼을 배치합니다.
 //
 // ◀ 버튼 → prevImage 함수 실행
 // ▶ 버튼 → nextImage 함수 실행
 //
 // 이전 버튼은 왼쪽에 배치합니다.
 // 다음 버튼은 오른쪽에 배치합니다.
 //
