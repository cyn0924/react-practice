 // 핵심 학습 내용
 // =====================================================
 // useState → 현재 카드 인덱스 상태 관리
 // currentIndex → 현재 표시 중인 카드 위치
 // setCurrentIndex → 현재 카드 위치 변경
 // cards → 슬라이드에 사용할 카드 데이터 배열
 // prevSlide → 이전 카드 이동 함수
 // nextSlide → 다음 카드 이동 함수
 // cards.length → 전체 카드 개수 확인
 // cards.length - 1 → 마지막 카드 인덱스 계산
 // 삼항 연산자 → 첫 카드와 마지막 카드의 순환 처리
 // map → 카드 개수만큼 페이지 표시 점 생성
 // onClick → 이전·다음 버튼 및 점 클릭 처리
 // className → 카드와 점에 CSS 스타일 적용
 // active → 현재 선택된 점 강조
 // 배열 인덱스 접근 → cards[currentIndex]
 // img src → 현재 카드 이미지 표시
 // img alt → 이미지 대체 텍스트 제공
 // key → React가 반복 생성한 요소를 구분
 // 함수형 상태 업데이트 → 이전 인덱스를 기준으로 다음 값 계산
 // 컴포넌트 재렌더링 → 상태 변경에 따라 카드 화면 업데이트


 // =====================================================
 // 가장 중요한 React 카드 슬라이드 작동 원리
 // =====================================================
 // 사용자가 이전 또는 다음 버튼 클릭
 // → onClick 이벤트 발생
 // → prevSlide 또는 nextSlide 함수 실행
 // → 현재 currentIndex 값 확인
 // → 이전 또는 다음 인덱스 계산
 // → setCurrentIndex로 상태 변경
 // → React 컴포넌트 재렌더링
 // → cards[currentIndex]에서 카드 데이터 선택
 // → 이미지, 제목, 설명, 카테고리 자동 변경
 // → 현재 위치에 해당하는 점에 active 클래스 적용
 //
 // 하단 페이지 표시 점을 클릭하면
 // → 클릭한 점의 index를 currentIndex에 저장
 // → 해당 위치의 카드로 바로 이동
 //
 // 핵심: useState로 현재 카드의 인덱스를 관리하고
 // 배열의 인덱스를 이용하여 카드 데이터를 선택하면
 // 하나의 카드 컴포넌트에서 여러 콘텐츠를
 // 이전·다음 버튼과 페이지 표시 점으로 전환할 수 있습니다.
 //
 // 참고: 이 코드는 한 번에 카드 하나를 교체하여 보여줍니다.
 // CSS 애니메이션이나 자동 재생 기능은 포함되어 있지 않습니다.
