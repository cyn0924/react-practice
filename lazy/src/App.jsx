 // =====================================================
 // App 컴포넌트 실행
 // → activeTab 초기값 "home" 설정
 // → renderPage에서 HomePage 선택
 // → Suspense 내부에 HomePage 렌더링
 // → lazy 컴포넌트의 Promise 결과 확인
 // → 필요한 경우 fallback 화면 표시
 // → 컴포넌트 준비 완료 후 홈 페이지 출력
 //
 // 사용자가 다른 메뉴 클릭
 // → onClick 이벤트 발생
 // → setActiveTab 실행
 // → activeTab 상태 변경
 // → React App 컴포넌트 재렌더링
 // → renderPage에서 해당 컴포넌트 선택
 // → Suspense를 통해 필요한 컴포넌트 표시
 // → 선택된 메뉴에 active 클래스 적용
