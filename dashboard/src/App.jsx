// React에서 컴포넌트를 만들기 위해 React와 useState Hook을 불러옵니다.
// useState는 사이드바 열림 상태와 현재 선택된 메뉴를 저장할 때 사용합니다.
import React, { useState } from "react";
import "./App.css";

// 사이드바 메뉴와 메인 콘텐트를 담당하는 App 컴포넌트입니다.
function App() {

  // 사이드바가 열려 있는지 여부를 저장합니다.
  // true이면 메뉴 이름까지 표시하고 false이면 아이콘만 표시됩니다.
  const [isSidebarOpen, setIsSidebarOpen] = useState(true);

  // 현재 선택된 메뉴의 id를 저장합니다.
  // 처음에는 dashboard 메뉴를 선택한 상태로 시작합니다.
  const [selectedMenu, setSelectedMenu] = useState("dashboard");

  // 사이드바에 표시할 메뉴 목록입니다.
  // 각 메뉴는 id, label, icon 정보를 가지고 있습니다.
  const menus = [
    { id: "dashboard", label: "대시보드", icon: "🏠" },
    { id: "users", label: "사용자 관리", icon: "👤" },
    { id: "products", label: "상품 관리", icon: "🛒" },
    { id: "orders", label: "주문 관리", icon: "📦" },
    { id: "settings", label: "설정", icon: "⚙️" },
  ];

  // 메뉴 id 별로 메인 화면에 표시할 제목과 설명을 저장합니다.
  // 선택된 메뉴에 따라 다른 콘텐츠를 보여주기 위해 사용합니다.
  const contentMap = {

    // 대시보드 화면에 표시할 내용입니다.
    dashboard: {
      title: "대시보드",
      desc: "전체 서비스 현황을 확인하는 페이지입니다.",
    },

    // 사용자 관리 화면에 표시할 내용
    users: {
      title: "사용자 관리",
      desc: "사용자 목록 및 관리 기능입니다.",
    },
    products: {
      title: "상품 관리",
      desc: "상품 등록 및 관리 기능입니다.",
    },
    orders: {
      title: "주문 관리",
      desc: "주문 처리 및 확인 기능입니다.",
    },
    settings: {
      title: "설정",
      desc: "서비스 설정 페이지입니다.",
    },
  };

  // selectedMenu에 해당하는 콘텐츠 객체를 가져옵니다.
  // 예를 들어 selectedMenu가 "users" 이면 사용자 관리 정보를 가져옵니다.
  const currentContent = contentMap[selectedMenu];

  // 화면에 표시할 JSX를 반환합니다.
  return (

    // 앱 전체를 감싸는 최상위 컨테이너입니다.
    <div className="app">

      {/* 왼쪽 사이드바 영역입니다. */}
      <aside

        // 사이드바 기본 클래스와 열림/닫힘 상태 클래스를 함께 적용합니다.
        // isSlidebarOpen이 true이면 open, false이면 closed 클래스를 추가합니다.
        className={`sidebar ${isSidebarOpen ? "open" : "closed"}`}
      >

        {/* 사이드바 상단의 접기/펼치기 버튼 영역입니다. */}
        <div className="sidebarHeader">
          <button

            // 클릭할 때마다 true와 false를 반대로 변경합니다.
            onClick={() => setIsSidebarOpen(!isSidebarOpen)}
            className="toggleButton"
          >

            {/* 사이드바가 열려있으면 ◀, 닫혀있으면 ▶를 표시합니다. */}
            {isSidebarOpen ? "◀" : "▶"}
          </button>
        </div>

        {/* 사이드바 메뉴 버튼들을 표시하는 영역입니다. */}
        <div className="menuList">

          {/* menus 배열의 메뉴를 하나씩 버튼으로 출력합니다. */}
          {menus.map((menu) => (

            // 메뉴 하나를 표시하는 버튼입니다.
            <button

              // React가 각각의 메뉴를 구분할 수 있도록 menu.id를 key로 사용합니다.
              key={menu.id}

              // 버튼을 클릭하면 선택된 메뉴 id를 상태에 저장합니다.
              onClick={() => setSelectedMenu(menu.id)}

              // 모든 메뉴 버튼에 menuButton 클래스를 적용합니다.
              // 현재 선택된 메뉴에는 active 클래스를 추가합니다.
              className={`menuButton ${
                selectedMenu === menu.id ? "active" : ""
              }`}
            >

              {/* 메뉴 아이콘을 표시하는 영역입니다. */}
              <span className="menuIcon">{menu.icon}</span>

              {/* 사이드바가 열려 있을 때만 메뉴 이름을 표시합니다. */}
              {isSidebarOpen && <span>{menu.label}</span>}
            </button>
          ))}
        </div>
      </aside>

      {/* 선택한 메뉴의 내용을 표시하는 메인 영역입니다. */}
      <main className="main">

        {/* 현재 선택된 메뉴의 제목을 화면에 표시합니다. */}
        <h1 className="title">{currentContent.title}</h1>

        {/* 현재 선택된 메뉴의 설명을 표시합니다. */}
        <p className="description">{currentContent.desc}</p>

        {/* 선택한 메뉴의 상세 내용을 보여주는 콘텐츠 박스입니다. */}
        <div className="contentBox">

          {/* 현재 선택된 메뉴의 이름을 제목으로 표시합니다. */}
          <h2 className="contentTitle">
            {currentContent.title} 페이지
          </h2>

          {/* 현재 선택된 메뉴의 이름을 강조하여 표시합니다. */}
          <p className="contentText">
            현재 선택된 메뉴는 <strong>{currentContent.title}</strong>입니다.
          </p>

          {/* 메뉴를 선택하여 화면의 내용이 바뀐다는 안내문구입니다. */}
          <p className="contentText">
            사이드바에서 메뉴를 선택하면 내용이 변경됩니다.
          </p>
        </div>
      </main>
    </div>
  );
}

export default App;




// =====================================================
// React 사이드바 메뉴 시스템 전체 실행 흐름
// =====================================================
// 1. React와 useState를 불러옵니다.
// 2. 사이드바의 열림 및 닫힘 상태를 관리합니다.
// 3. 현재 선택된 메뉴를 상태로 저장합니다.
// 4. 대시보드, 사용자, 상품, 주문, 설정 메뉴를 준비합니다.
// 5. 각 메뉴에 해당하는 콘텐츠 데이터를 준비합니다.
// 6. 현재 선택된 메뉴의 콘텐츠를 가져옵니다.
// 7. 사용자가 사이드바 열기 및 닫기 버튼을 클릭합니다.
// 8. 사이드바의 상태에 따라 너비와 메뉴 표시가 변경됩니다.
// 9. 사용자가 사이드바에서 원하는 메뉴를 선택합니다.
// 10. 선택된 메뉴에 active 클래스를 적용합니다.
// 11. 선택한 메뉴에 맞는 제목과 설명을 표시합니다.
// 12. React 상태 변경에 따라 화면을 자동 업데이트합니다.
// =====================================================


// =====================================================
// 1단계. React 기능 및 CSS 불러오기
// =====================================================
// React는 컴포넌트를 생성하기 위해 사용합니다.
// useState는 사이드바와 메뉴 선택 상태를 관리합니다.
// App.css는 사이드바, 메뉴 버튼, 콘텐츠 디자인을 담당합니다.


// =====================================================
// 2단계. App 컴포넌트 생성
// =====================================================
// App은 전체 사이드바 메뉴 시스템을 관리합니다.
//
// 주요 역할
// 사이드바 열기 및 닫기
// 메뉴 데이터 관리
// 선택된 메뉴 상태 관리
// 메뉴 클릭 이벤트 처리
// 활성 메뉴 스타일 적용
// 선택된 메뉴의 콘텐츠 표시
//
// 하나의 App 컴포넌트에서 전체 화면을 구성합니다.


// =====================================================
// 3단계. 사이드바 열림 상태 관리
// =====================================================
// isSidebarOpen은 사이드바가 열려 있는지 저장합니다.
//
// useState(true)로 초기값을 설정합니다.
//
// true  → 사이드바 펼쳐진 상태
// false → 사이드바 접힌 상태
//
// 처음 실행하면 사이드바가 펼쳐져 있습니다.


// =====================================================
// 4단계. 현재 선택된 메뉴 상태 관리
// =====================================================
// selectedMenu는 현재 선택된 메뉴의 ID를 저장합니다.
//
// 초기값은 "dashboard"입니다.
//
// 따라서 처음 실행하면 대시보드 메뉴가 선택됩니다.
//
// 저장 가능한 메뉴 ID
// dashboard → 대시보드
// users     → 사용자 관리
// products  → 상품 관리
// orders    → 주문 관리
// settings  → 설정
//
// 사용자가 메뉴를 클릭하면 selectedMenu가 변경됩니다.


// =====================================================
// 5단계. 사이드바 메뉴 데이터 준비
// =====================================================
// menus 배열에 사이드바 메뉴 5개를 저장합니다.
//
// 각 메뉴에는 다음 정보가 있습니다.
//
// id    → 메뉴 고유 ID
// label → 화면에 표시할 메뉴 이름
// icon  → 메뉴 아이콘
//
// 예시
// dashboard → 대시보드 → 🏠
// users → 사용자 관리 → 👤
// products → 상품 관리 → 🛒
// orders → 주문 관리 → 📦
// settings → 설정 → ⚙️
//
// 배열을 이용하므로 메뉴가 추가되어도 반복 출력할 수 있습니다.


// =====================================================
// 6단계. 메뉴별 콘텐츠 데이터 준비
// =====================================================
// contentMap 객체에 각 메뉴의 콘텐츠를 저장합니다.
//
// 각 메뉴에는 다음 데이터가 있습니다.
//
// title → 콘텐츠 제목
// desc  → 콘텐츠 설명
//
// 메뉴 ID를 객체의 속성 이름으로 사용합니다.
//
// 예시
// contentMap.dashboard
// → 대시보드 제목과 설명
//
// contentMap.users
// → 사용자 관리 제목과 설명
//
// 메뉴 선택에 따라 서로 다른 콘텐츠를 표시합니다.


// =====================================================
// 7단계. 대시보드 콘텐츠 설정
// =====================================================
// dashboard 메뉴를 선택했을 때 표시할 데이터입니다.
//
// 제목: 대시보드
// 설명: 전체 서비스 현황을 확인하는 페이지입니다.
//
// 처음 실행하면 이 콘텐츠가 표시됩니다.


// =====================================================
// 8단계. 사용자 관리 콘텐츠 설정
// =====================================================
// users 메뉴를 선택했을 때 표시할 데이터입니다.
//
// 제목: 사용자 관리
// 설명: 사용자 목록 및 관리 기능입니다.
//
// 사용자 관리 메뉴를 클릭하면
// 메인 콘텐츠가 이 내용으로 변경됩니다.


// =====================================================
// 9단계. 상품 관리 콘텐츠 설정
// =====================================================
// products 메뉴를 선택했을 때 표시할 데이터입니다.
//
// 제목: 상품 관리
// 설명: 상품 등록 및 관리 기능입니다.
//
// 상품 관리 메뉴를 클릭하면
// 메인 콘텐츠가 이 내용으로 변경됩니다.


// =====================================================
// 10단계. 주문 관리 콘텐츠 설정
// =====================================================
// orders 메뉴를 선택했을 때 표시할 데이터입니다.
//
// 제목: 주문 관리
// 설명: 주문 처리 및 확인 기능입니다.
//
// 주문 관리 메뉴를 클릭하면
// 메인 콘텐츠가 이 내용으로 변경됩니다.


// =====================================================
// 11단계. 설정 콘텐츠 설정
// =====================================================
// settings 메뉴를 선택했을 때 표시할 데이터입니다.
//
// 제목: 설정
// 설명: 서비스 설정 페이지입니다.
//
// 설정 메뉴를 클릭하면
// 메인 콘텐츠가 이 내용으로 변경됩니다.


// =====================================================
// 12단계. 현재 선택된 메뉴 콘텐츠 가져오기
// =====================================================
// currentContent는 현재 선택된 메뉴의 데이터를 저장합니다.
//
// contentMap[selectedMenu]을 이용하여 데이터를 가져옵니다.
//
// 예시
// selectedMenu가 "dashboard"이면
// → contentMap.dashboard
//
// selectedMenu가 "products"이면
// → contentMap.products
//
// selectedMenu가 변경되면 currentContent도 다시 계산됩니다.
//
// 이를 통해 하나의 메인 영역에서
// 메뉴별로 다른 제목과 설명을 표시할 수 있습니다.


// =====================================================
// 13단계. JSX 전체 화면 구성
// =====================================================
// return에서 사용자에게 보여줄 화면을 구성합니다.
//
// 전체 화면은 크게 두 영역으로 나뉩니다.
//
// 왼쪽 → 사이드바 메뉴 영역
// 오른쪽 → 메인 콘텐츠 영역
//
// app 클래스는 전체 레이아웃을 감쌉니다.
//
// React 상태에 따라 사이드바와 콘텐츠가 변경됩니다.


// =====================================================
// 14단계. 사이드바 영역 구성
// =====================================================
// aside 요소를 사용하여 사이드바를 만듭니다.
//
// 모든 사이드바에는 sidebar 클래스를 적용합니다.
//
// isSidebarOpen 값에 따라 추가 클래스를 설정합니다.
//
// true → open 클래스
// false → closed 클래스
//
// CSS에서 open과 closed의 너비 등을 다르게 설정하면
// 사이드바 펼치기 및 접기 기능을 구현할 수 있습니다.


// =====================================================
// 15단계. 사이드바 펼치기 및 접기 버튼
// =====================================================
// sidebarHeader 안에 toggleButton을 배치합니다.
//
// 사용자가 버튼을 클릭하면
// setIsSidebarOpen(!isSidebarOpen)이 실행됩니다.
//
// 현재 상태가 true이면 false로 변경합니다.
// 현재 상태가 false이면 true로 변경합니다.
//
// 실행 흐름
// 버튼 클릭
// → onClick 이벤트 발생
// → setIsSidebarOpen 실행
// → 사이드바 상태 변경
// → React 컴포넌트 재렌더링
// → 사이드바 펼침 또는 접힘


// =====================================================
// 16단계. 사이드바 상태별 화살표 변경
// =====================================================
// isSidebarOpen 값에 따라 화살표를 변경합니다.
//
// true  → ◀
// false → ▶
//
// ◀ 아이콘은 사이드바를 접을 때 표시됩니다.
// ▶ 아이콘은 사이드바를 펼칠 때 표시됩니다.
//
// 삼항 연산자를 이용하여 아이콘을 변경합니다.


// =====================================================
// 17단계. 사이드바 메뉴 목록 반복 출력
// =====================================================
// menuList는 모든 메뉴 버튼을 감싸는 영역입니다.
//
// menus 배열을 map으로 반복합니다.
//
// 메뉴 데이터 하나마다 button 요소를 생성합니다.
//
// 메뉴 구성
// 대시보드
// 사용자 관리
// 상품 관리
// 주문 관리
// 설정
//
// 각 메뉴의 key에는 menu.id를 사용합니다.
//
// 메뉴가 추가되면 버튼도 자동으로 생성됩니다.


// =====================================================
// 18단계. 메뉴 버튼 클릭 이벤트 처리
// =====================================================
// 사용자가 메뉴 버튼을 클릭하면 onClick이 실행됩니다.
//
// setSelectedMenu(menu.id)로 선택한 메뉴 ID를 저장합니다.
//
// 실행 흐름
// 메뉴 버튼 클릭
// → onClick 이벤트 발생
// → setSelectedMenu 실행
// → selectedMenu 상태 변경
// → currentContent 변경
// → React 화면 자동 업데이트
//
// 예시
// 상품 관리 클릭
// → selectedMenu = "products"
// → 상품 관리 콘텐츠 표시


// =====================================================
// 19단계. 현재 선택된 메뉴 활성화 표시
// =====================================================
// selectedMenu와 menu.id를 비교합니다.
//
