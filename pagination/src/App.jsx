import React, { useState } from "react";
import "./App.css";

// 페이지네이션 실습용 상품 데이터입니다.
// Array.from()을 사용하여 상품 30개를 자동으로 생성합니다.
// 배열의 각 상품은 id, name, price 정보를 가집니다.
const products = Array.from({ length: 30 }, (_, index) => ({

  // 상품을 구분하기 위한 고유 번호입니다.
  // index는 0부터 시작하므로 1을 더해 1번 부터 시작하게 됩니다.
  id: index + 1,

  // 상품 이름을 자동으로 만듭니다.
  // 예를 들어 index가 0이면 "상품1"이 됩니다.
  name: `상품 ${index + 1}`,

  // 상품 가격을 자동으로 게산합니다.
  // 첫 상품은 10,000원이고 상품마다 1,500원씩 증가합니다.
  price: 10000 + index * 1500,
}));

// 상품 목록과 페이지네이션 기능을 담당하는 App 컴포넌트입니다.
function App() {

  // 현재 사용자가 보고 있는 페이지 번호를 저장합니다.
  // 처음 화면에서는 1페이지를 보여주므로 초기값은 1입니다.
  const [currentPage, setCurrentPage] = useState(1);

  // 한 페이지에 표시할 상품 개수를 저장합니다.
  // 처음에는 한 페이지에 5개씩 표시합니다.
  const [itemsPerPage, setItemsPerPage] = useState(5);

  // 전체 페이지 수를 계산합니다.
  // 전체 상품 수를 페이지당 상품 수로 나눕니다.
  // 상품 수가 딱 나누어지지 않으면 Math.ceil()이 올림 처리합니다.
  const totalPages = Math.ceil(
    products.length / itemsPerPage
  );

  // 현재 페이지에서 시작할 상품의 배열 인덱스를 계산합니다.
  // 배열 인덱스는 0부터 시작하므로 현재 페이지에서 1을 뺍니다.
  // 예를 들어 1페이지이면 시작 인덱스는 0입니다.
  const startIndex = (currentPage - 1) * itemsPerPage;

  // 현재 페이지에서 끝나는 배열 인덱스를 계산합니다.
  // 시작 인덱스에 페이지당 상품 개수를 더합니다.
  const endIndex = startIndex + itemsPerPage;

  // 전체 상품 배열에서 현재 페이지에 필요한 상품만 추출합니다.
  // 예를 들어 5개씩 보기에서 2페이지라면 6번째부터 10번째 상품이 추출됩니다.
  const currentProducts = products.slice(
    startIndex,
    endIndex
  );

  // 페이지 번호 버튼을 클릭했을 때 실행되는 함수입니다.
  // 이동하려는 페이지 번호를 매개변수로 전달받습니다.
  const handlePageChange = (pageNumber) => {

    // 1페이지보다 작거나 전체 페이지 수보다 큰 경우에는 존재하지 않는 페이지이므로 함수 실행을 중단합니다.
    if (pageNumber < 1 || pageNumber > totalPages) {
      return;
    }

    // 유효한 페이지 번호라면 현재 페이지 상태를 변경합니다.
    // 상태가 변경되면 React가 화면을 다시 렌더링합니다.
    setCurrentPage(pageNumber);
  };

  // 한 페이지에 표시할 상품 개수가 변경될 때 실행되는 함수입니다.
  const handleItemsPerPage = (event) => {

    // select에서 선택한 value는 문자열이므로 Number()를 사용하여 숫자로 변환합니다.
    // 변환된 값을 itemsPerPage 상태에 저장합니다.
    setItemsPerPage(Number(event.target.value));

    // 페이지당 상품 개수가 바뀌면 데이터 구성이 달라질 수 있으므로 안전하게 첫 페이지로 이동합니다.
    setCurrentPage(1);
  };

 // =====================================================
 // React 상품 리스트 페이지네이션 전체 실행 흐름
 // =====================================================
 // 1. Array.from()으로 상품 30개의 데이터를 생성합니다.
 // 2. 현재 페이지와 페이지당 상품 개수를 설정합니다.
 // 3. 전체 상품 수를 기준으로 총 페이지 수를 계산합니다.
 // 4. 현재 페이지에서 보여줄 상품의 시작 위치를 계산합니다.
 // 5. slice()로 해당 페이지의 상품만 추출합니다.
 // 6. 추출한 상품을 카드 형태로 화면에 표시합니다.
 // 7. 사용자가 페이지 번호를 클릭하면 페이지를 변경합니다.
 // 8. 처음, 이전, 다음, 마지막 버튼으로 페이지를 이동합니다.
 // 9. 5개씩 보기 또는 10개씩 보기를 선택할 수 있습니다.
 // 10. 페이지가 변경되면 상품 목록이 자동 업데이트됩니다.
 // =====================================================


 // =====================================================
 // 1단계. React 기능 및 CSS 불러오기
 // =====================================================
 // useState는 현재 페이지와 상품 표시 개수를 관리합니다.
 // App.css는 상품 목록과 페이지네이션 디자인을 담당합니다.


 // =====================================================
 // 2단계. 상품 데이터 30개 생성
 // =====================================================
 // Array.from()을 이용하여 상품 30개를 자동 생성합니다.
 //
 // 각 상품은 다음 정보를 가지고 있습니다.
 // id    → 상품 고유번호
 // name  → 상품 이름
 // price → 상품 가격
 //
 // index는 0부터 시작하므로 id에는 1을 더합니다.
 // 상품 가격은 10,000원부터 1,500원씩 증가합니다.
 //
 // 예시
 // 상품 1 → 10,000원
 // 상품 2 → 11,500원
 // 상품 3 → 13,000원
 //
 // 총 30개의 상품 데이터가 생성됩니다.


 // =====================================================
 // 3단계. 현재 페이지 상태 관리
 // =====================================================
 // currentPage는 현재 사용자가 보고 있는 페이지입니다.
 // 초기값은 1이므로 처음에는 1페이지가 표시됩니다.
 //
 // 사용자가 페이지 버튼을 클릭하면 setCurrentPage가 실행됩니다.
 // 페이지 상태가 변경되면 React가 화면을 다시 렌더링합니다.


 // =====================================================
 // 4단계. 페이지당 상품 개수 관리
 // =====================================================
 // itemsPerPage는 한 페이지에 표시할 상품 개수입니다.
 // 초기값은 5이므로 한 페이지에 상품 5개가 표시됩니다.
 //
 // 사용자는 5개씩 보기 또는 10개씩 보기를 선택할 수 있습니다.
 // 선택한 개수에 따라 전체 페이지 수가 변경됩니다.


 // =====================================================
 // 5단계. 전체 페이지 개수 계산
 // =====================================================
 // 전체 상품 개수를 페이지당 상품 개수로 나눕니다.
 // Math.ceil()을 사용하여 소수점을 올림 처리합니다.
 //
 // 계산 공식
 // 총 페이지 수 = 전체 상품 수 / 페이지당 상품 수
 //
 // 예시
 // 상품 30개 / 5개씩 보기 = 총 6페이지
 // 상품 30개 / 10개씩 보기 = 총 3페이지
 //
 // 상품이 남아 있으면 마지막 페이지를 추가합니다.
 // 예시: 상품 32개 / 5개씩 보기 = 총 7페이지


 // =====================================================
 // 6단계. 현재 페이지 상품의 시작 위치 계산
 // =====================================================
 // startIndex는 현재 페이지에서 표시할 첫 상품의 위치입니다.
 //
 // 계산 공식
 // (현재 페이지 - 1) × 페이지당 상품 개수
 //
 // 예시: 5개씩 보기
 // 1페이지 → 시작 인덱스 0
 // 2페이지 → 시작 인덱스 5
 // 3페이지 → 시작 인덱스 10
 //
 // 배열의 인덱스는 0부터 시작합니다.


 // =====================================================
 // 7단계. 현재 페이지 상품의 마지막 위치 계산
 // =====================================================
 // endIndex는 상품을 추출할 범위의 끝 위치입니다.
 //
 // 계산 공식
 // 시작 인덱스 + 페이지당 상품 개수
 //
 // 예시: 5개씩 보기
 // 1페이지 → 0부터 5 전까지
 // 2페이지 → 5부터 10 전까지
 // 3페이지 → 10부터 15 전까지
 //
 // slice()에서는 endIndex 위치의 상품은 포함하지 않습니다.


 // =====================================================
 // 8단계. 현재 페이지 상품 데이터 추출
 // =====================================================
 // slice()를 사용하여 필요한 상품만 추출합니다.
 //
 // products.slice(startIndex, endIndex)
 //
 // 예시: 5개씩 보기
 // 1페이지 → 상품 1~5
 // 2페이지 → 상품 6~10
 // 3페이지 → 상품 11~15
 //
 // 추출된 상품 목록은 currentProducts에 저장됩니다.
 // 원본 products 배열은 변경되지 않습니다.


 // =====================================================
 // 9단계. 페이지 번호 변경 처리
 // =====================================================
 // 사용자가 페이지 번호 버튼을 누르면 실행됩니다.
 //
 // 페이지 번호 클릭 → handlePageChange 실행
 // → 이동할 페이지 번호 검사
 // → setCurrentPage 실행
 // → 현재 페이지 변경
 // → 상품 목록 자동 업데이트
 //
 // 1보다 작은 페이지나 마지막 페이지를 초과한 번호는
 // 이동하지 않도록 제한합니다.


 // =====================================================
 // 10단계. 페이지당 표시 개수 변경
 // =====================================================
 // 사용자가 5개씩 보기 또는 10개씩 보기를 선택합니다.
 //
 // 선택 변경 → handleItemsPerPage 실행
 // → 선택한 값을 숫자로 변환
 // → setItemsPerPage로 상태 변경
 // → 전체 페이지 수 다시 계산
 // → 현재 페이지를 1페이지로 초기화
 //
 // 표시 개수가 바뀌면 첫 페이지부터 다시 보여줍니다.


 // =====================================================
 // 11단계. JSX 전체 화면 구성
 // =====================================================
 // return에서 사용자가 보는 페이지네이션 화면을 만듭니다.
 //
 // 화면 구성
 // 1. 상품 리스트 제목
 // 2. 전체 상품 개수
 // 3. 현재 페이지 정보
 // 4. 페이지당 상품 개수 선택창
 // 5. 현재 페이지의 상품 목록
 // 6. 페이지네이션 버튼
 //
 // 페이지 상태가 변경되면 상품 목록도 변경됩니다.


 // =====================================================
 // 12단계. 상품 리스트 제목 및 전체 개수 출력
 // =====================================================
 // 화면 상단에 "상품 리스트" 제목을 표시합니다.
 // "React 페이지네이션 실습" 설명을 표시합니다.
 //
 // products.length로 전체 상품 개수를 계산합니다.
 // 예시: 전체 30개
 //
 // 현재 페이지와 관계없이 전체 상품 개수를 표시합니다.


 // =====================================================
 // 13단계. 현재 페이지 정보 표시
 // =====================================================
 // toolbar 영역에서 현재 페이지와 전체 페이지를 표시합니다.
 //
 // 예시
 // 현재 1 / 6 페이지
 // 현재 2 / 6 페이지
 // 현재 3 / 6 페이지
 //
 // 사용자가 페이지를 이동하면 숫자가 자동 변경됩니다.


 // =====================================================
 // 14단계. 상품 표시 개수 선택창 구현
 // =====================================================
 // select 요소로 페이지당 상품 개수를 선택합니다.
 //
 // 선택 항목
 // 5개씩 보기
 // 10개씩 보기
 //
 // 선택값이 변경되면 onChange 이벤트가 발생합니다.
 // handleItemsPerPage 함수가 실행됩니다.
 // 변경된 개수에 맞춰 상품 목록을 다시 표시합니다.


 // =====================================================
 // 15단계. 현재 페이지 상품 목록 출력
 // =====================================================
 // currentProducts 배열을 map으로 반복 출력합니다.
 //
 // 각 상품은 카드 형태로 표시됩니다.
 //
 // 상품 카드 구성
 // 상품 아이콘
 // 상품 이름
 // 상품번호
 // 상품 가격
 //
 // key에는 상품의 고유번호인 id를 사용합니다.
 // 현재 페이지에 해당하는 상품만 화면에 나타납니다.


 // =====================================================
 // 16단계. 상품 가격 표시
 // =====================================================
 // toLocaleString()으로 상품 가격에 쉼표를 추가합니다.
 //
 // 예시
 // 10000 → 10,000
 // 11500 → 11,500
 // 25000 → 25,000
 //
 // 가격 뒤에 "원"을 붙여 표시합니다.


 // =====================================================
 // 17단계. 페이지네이션 버튼 영역 구성
 // =====================================================
 // nav 요소 안에 페이지 이동 버튼을 배치합니다.
 //
 // 버튼 구성
 // 처음
 // 이전
 // 페이지 번호
 // 다음
 // 마지막
 //
 // aria-label로 페이지 이동 영역의 용도를 알려줍니다.
 // 사용자는 버튼을 클릭하여 원하는 페이지로 이동합니다.


 // =====================================================
 // 18단계. 처음 페이지 이동 버튼
 // =====================================================
 // 처음 버튼을 누르면 1페이지로 이동합니다.
 //
 // 처음 클릭 → handlePageChange(1)
 // → currentPage를 1로 변경
 // → 첫 번째 상품 목록 표시
 //
 // 현재 1페이지라면 버튼이 비활성화됩니다.


 // =====================================================
 // 19단계. 이전 페이지 이동 버튼
 // =====================================================
 // 이전 버튼을 누르면 현재 페이지에서 1을 뺍니다.
 //
 // 예시
 // 4페이지에서 이전 클릭 → 3페이지
 // 3페이지에서 이전 클릭 → 2페이지
 //
 // 현재 1페이지라면 이전 버튼이 비활성화됩니다.


 // =====================================================
 // 20단계. 페이지 번호 버튼 자동 생성
 // =====================================================
 // Array.from()을 사용하여 전체 페이지 번호를 생성합니다.
 //
 // 예시: 총 6페이지
 // 1, 2, 3, 4, 5, 6
 //
 // 생성된 페이지 번호를 map으로 반복 출력합니다.
 // 각 페이지 번호는 클릭할 수 있는 버튼으로 표시됩니다.
 //
 // 페이지 번호 클릭 → handlePageChange 실행
 // → 선택한 페이지로 이동
 // → 해당 페이지의 상품 목록 표시


 // =====================================================
 // 21단계. 현재 페이지 버튼 활성화 표시
 // =====================================================
 // 현재 선택된 페이지 번호를 확인합니다.
 //
 // currentPage와 pageNumber가 같으면
 // active 클래스를 적용합니다.
 //
 // 예시
 // 현재 3페이지라면 숫자 3 버튼에 active 클래스 적용
 //
 // CSS를 통해 선택된 페이지 버튼을 강조할 수 있습니다.
 // aria-current="page"로 현재 페이지임을 알려줍니다.


 // =====================================================
 // 22단계. 다음 페이지 이동 버튼
 // =====================================================
 // 다음 버튼을 누르면 현재 페이지에 1을 더합니다.
 //
 // 예시
 // 1페이지에서 다음 클릭 → 2페이지
 // 2페이지에서 다음 클릭 → 3페이지
 //
 // 마지막 페이지에 도착하면 다음 버튼이 비활성화됩니다.


 // =====================================================
 // 23단계. 마지막 페이지 이동 버튼
 // =====================================================
 // 마지막 버튼을 누르면 전체 페이지의 마지막으로 이동합니다.
 //
 // 예시
 // 총 6페이지라면 마지막 클릭 → 6페이지
 //
 // 마지막 페이지에 도착하면 버튼이 비활성화됩니다.


 // =====================================================
 // 24단계. 페이지 변경 시 화면 자동 업데이트
 // =====================================================
 // 사용자가 페이지 번호를 클릭합니다.
 // setCurrentPage로 현재 페이지 상태가 변경됩니다.
 //
 // React가 App 컴포넌트를 다시 렌더링합니다.
 // startIndex와 endIndex가 다시 계산됩니다.
 // slice()로 새로운 상품 목록을 추출합니다.
 // currentProducts가 변경됩니다.
 // 화면에 새로운 페이지의 상품 목록이 표시됩니다.
 //
 // 별도의 새로고침 없이 상품 목록이 변경됩니다.


 // =====================================================
 // 최종 실행 결과
 // =====================================================
 // 1. 상품 30개를 자동 생성합니다.
 // 2. 처음에는 상품 5개를 표시합니다.
 // 3. 총 6개의 페이지 번호가 생성됩니다.
 // 4. 페이지 번호를 클릭하면 해당 상품을 보여줍니다.
 // 5. 처음, 이전, 다음, 마지막 버튼으로 이동합니다.
 // 6. 현재 페이지 번호가 강조 표시됩니다.
 // 7. 첫 페이지와 마지막 페이지에서는 이동 버튼이 제한됩니다.
 // 8. 10개씩 보기를 선택하면 총 3페이지로 변경됩니다.
 // 9. 표시 개수를 변경하면 1페이지로 돌아갑니다.
 // 10. 페이지 변경 결과가 화면에 자동 반영됩니다.


 // =====================================================
 // 핵심 학습 내용
 // =====================================================
 // useState → 현재 페이지 및 표시 개수 상태 관리
 // Array.from → 상품 데이터와 페이지 번호 자동 생성
 // length → 전체 상품 개수 확인
 // Math.ceil → 전체 페이지 수 올림 계산
 // slice → 현재 페이지에 필요한 상품만 추출
 // map → 상품 목록 및 페이지 번호 반복 출력
 // onClick → 페이지 이동 버튼 클릭 처리
 // onChange → 페이지당 상품 개수 변경 처리
 // setCurrentPage → 현재 페이지 변경
 // setItemsPerPage → 페이지당 표시 개수 변경
 // disabled → 이동할 수 없는 버튼 비활성화
 // className → 현재 선택한 페이지 스타일 적용
 // aria-label → 페이지네이션 영역 설명
 // aria-current → 현재 페이지 정보 제공
 // toLocaleString → 상품 가격에 천 단위 쉼표 추가


 // =====================================================
 // 가장 중요한 React 페이지네이션 작동 원리
 // =====================================================
 // 사용자 페이지 번호 클릭
 // → onClick 이벤트 발생
 // → handlePageChange 함수 실행
 // → setCurrentPage로 현재 페이지 변경
 // → startIndex와 endIndex 다시 계산
 // → slice로 해당 페이지 상품 추출
 // → currentProducts 변경
 // → React 화면 자동 업데이트
 //
 // 핵심: 전체 상품 데이터를 모두 화면에 출력하지 않고
 // 현재 페이지에 필요한 상품만 잘라서 표시하는 구조입니다.
 //
 // 참고: 이 예제는 클라이언트 측 페이지네이션입니다.
 // 모든 상품 데이터가 이미 준비되어 있고,
 // 페이지를 변경할 때 서버에 새로 요청하지 않습니다.
 // =====================================================


  // 화면 표시
  return (
    <div className="app">
      <div className="container">
        <header className="header">
          <div>
            <h1>상품 리스트</h1>
            <p>React 페이지네이션 실습</p>
          </div>

          {/* 전체 상품 개수를 표시합니다. */}
          <span className="total-count">
            전체 {products.length}개
          </span>
        </header>

        {/* 현재 페이지 정보와 페이지당 표시 개수를 선택하는 영역 */}
        <div className="toolbar">

          {/* 현재 페이지와 전체 페이지수를 표시합니다. */}
          <span>
            현재 {currentPage} / {totalPages} 페이지
          </span>

          {/* 한 페이지에 몇 개의 상품을 표시할지 선택하는 select입니다. */}
          <select

            // 현재 선택된 표시 개수를 select 값과 연결합니다.
            value={itemsPerPage}
            // 선택된 값이 바뀌면 handleItemPerPage 함수를 실행합니다.
            onChange={handleItemsPerPage}
          >
            <option value={5}>5개씩 보기</option>
            <option value={10}>10개씩 보기</option>
          </select>
        </div>

        {/* 현재 페이지에 해당하는 상품들을 표시하는 영역입니다. */}
        <div className="product-list">

          {/* 배열을 map으로 반복하여 상품 카드를 만듭니다. */}
          {currentProducts.map((product) => (

            // 상품 하나를 감싸는 카드입니다.
            // React가 상품을 구분할 수 있도록 product.id를 key로 사용합니다.
            <div className="product-card" key={product.id}>

              {/* 실제 상품 이미지 대신 상자 이모지를 표시하는 영역입니다. */}
              <div className="product-image">📦</div>

              {/* 상품 이름과 상품 번호를 표시하는 영역입니다. */}
              <div className="product-info">

                {/* 상품이름 */}
                <h3>{product.name}</h3>
                {/* 고유번호 */}
                <p>상품번호 : {product.id}</p>
              </div>
              
              {/* 상품 가격 */}
              <div className="product-price">

                {/* 숫자에 천단위 쉼표 표시형식 */}
                {product.price.toLocaleString("ko-KR")}원
              </div>
            </div>
          ))}
        </div>

        {/* 페이지 번호와 이동 버튼을 감싸는 영역입니다. */}
        {/* nav는 페이지 이동 메뉴임을 의미하는 시멘틱 태그입니다. */}
        <nav
          className="pagination"

          // 스크린 리더 사용자에게 이 영역이 상품 목록 페이지 이동 영역임을 알려줍니다.
          aria-label="상품 목록 페이지"
        >

          {/* 첫번째 페이지로 이동하는 버튼 */}
          <button
            type="button"

            // 클릭하면 1페이지로 이동
            onClick={() => handlePageChange(1)}
            // 현재 1페이지라면 이미 첫 페이지이므로 버튼을 비활성화합니다.
            disabled={currentPage === 1}
          >
            처음
          </button>

          {/* 이전 페이지로 이동하는 버튼 */}
          <button
            type="button"

            // 현재 페이지에서 1을 뺀 페이지로 이동합니다.
            onClick={() =>
              handlePageChange(currentPage - 1)
            }
            // 현재 1페이지라면 이전 페이지가 없으므로 비활성화합니다.
            disabled={currentPage === 1}
          >
            이전
          </button>

          {/* 전체 페이지 번호를 배열로 만든 뒤 버튼으로 반복 출력합니다. */}
          {Array.from(
            { length: totalPages },

            // 배열의 각 위치를 이용하여 페이지 번호를 만듭니다.
            // index는 0부터 시작하므로 1을 더합니다.
            (_, index) => index + 1
          ).map((pageNumber) => (

            // 페이지 번호 하나를 버튼으로 표시합니다.
            <button
              type="button"

              // 페이지 번호를 고유한 key로 사용합니다.
              key={pageNumber}

              // 현재 페이지와 같은 번호이면 active 클래스를 적용합니다.
              // 현재 페이지가 아니면 빈 문자열을 적용합니다.
              className={
                currentPage === pageNumber ? "active" : ""
              }

              // 현재 선택된 페이지임을 웹 접근성 속성으로 알려줍니다.
              // 현재 페이지가 아니면 속성을 지정하지 않습니다.
              aria-current={
                currentPage === pageNumber
                  ? "page"
                  : undefined
              }

              // 클릭한 페이지 번호를 handlePageChange 함수에 전달합니다.
              onClick={() =>
                handlePageChange(pageNumber)
              }
            >
              {/* 버튼 안에 페이지 번호를 표시합니다. */}
              {pageNumber}
            </button>
          ))}

          {/* 다음 페이지 이동 버튼 */}
          <button
            type="button"
            onClick={() =>
              handlePageChange(currentPage + 1)
            }

            // 마지막 페이지라면 다음 페이지가 없으므로 비활성화 합니다.
            disabled={currentPage === totalPages}
          >
            다음
          </button>

          {/* 가장 마지막 페이지로 이동하는 버튼 */}
          <button
            type="button"
            onClick={() => handlePageChange(totalPages)}

            // 현재 마지막 페이지라면 버튼을 비활성화합니다.
            disabled={currentPage === totalPages}
          >
            마지막
          </button>
        </nav>
      </div>
    </div>
  );
}

export default App;