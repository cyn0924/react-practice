// =====================================================
// 13단계. 메시지 고유번호 관리
// =====================================================
// nextIdRef는 새 메시지에 사용할 ID를 관리합니다.
//
// useRef(3)으로 초기값을 설정합니다.
//
// 기본 메시지는 ID 1과 2를 사용합니다.
//
// 따라서 새 메시지는 ID 3부터 시작합니다.
//
// nextIdRef.current++를 실행하면
// 현재 ID를 사용한 뒤 다음 ID로 증가합니다.
//
// 예시
// 사용자 메시지 → ID 3
// 자동 응답 → ID 4
// 다음 사용자 메시지 → ID 5
//
// useRef는 값이 변경되어도
// 컴포넌트를 다시 렌더링하지 않습니다.


// =====================================================
// 14단계. 빠른 답장 메시지 목록
// =====================================================
// quickReplies에는 미리 작성한 메시지 4개가 있습니다.
//
// 안녕하세요
// 오늘 일정 알려줘
// React 공부 중이에요
// 도움이 필요해요
//
// useMemo로 배열을 생성합니다.
//
// 의존성 배열이 []이므로
// 일반적인 재렌더링에서는 동일한 배열을 재사용합니다.
//
// 사용자는 직접 입력하지 않고
// 버튼을 클릭하여 메시지를 보낼 수 있습니다.


// =====================================================
// 15단계. 온라인 상태 자동 변경
// =====================================================
// 첫 번째 useEffect에서 setInterval을 실행합니다.
//
// setInterval은 일정 시간마다
// 함수를 반복 실행하는 기능입니다.
//
// 현재 반복 간격은 8000밀리초입니다.
//
// 8000밀리초 = 8초
//
// 8초마다 setIsOnline을 실행합니다.
//
// 이전 상태가 true이면 false로 변경합니다.
// 이전 상태가 false이면 true로 변경합니다.
//
// 따라서 온라인과 오프라인 상태가 반복 전환됩니다.
//
// 이 기능은 실제 접속 상태가 아닌 시뮬레이션입니다.


// =====================================================
// 16단계. 온라인 상태 타이머 정리
// =====================================================
// useEffect의 정리 함수에서 clearInterval을 실행합니다.
//
// 컴포넌트가 종료되면
// 온라인 상태 변경 타이머를 정리합니다.
//
// 타이머가 불필요하게 계속 실행되는 것을 방지합니다.
//
// 개발 환경의 React StrictMode에서는
// Effect의 설정과 정리 과정이 추가 실행될 수 있습니다.


// =====================================================
// 17단계. 새 메시지 자동 스크롤
// =====================================================
// 두 번째 useEffect는 messages 또는 isTyping이
// 변경될 때마다 실행됩니다.
//
// chatBodyRef.current가 존재하는지 확인합니다.
//
// scrollHeight는 전체 채팅 콘텐츠의 높이입니다.
//
// scrollTop은 현재 세로 스크롤 위치입니다.
//
// scrollTop에 scrollHeight를 대입하면
// 스크롤이 가능한 범위의 맨 아래로 이동합니다.
//
// 따라서 새 메시지나 입력 중 표시가 추가되면
// 최신 대화가 보이도록 화면이 이동합니다.


// =====================================================
// 18단계. 처음 실행할 때 입력창 포커스
// =====================================================
// 세 번째 useEffect는 컴포넌트 마운트 시 실행됩니다.
//
// inputRef.current?.focus()를 사용합니다.
//
// ?.는 선택적 연결 연산자입니다.
//
// inputRef.current가 존재할 때만
// focus() 함수를 실행합니다.
//
// 화면이 열리면 사용자가 입력창을 클릭하지 않아도
// 바로 메시지를 입력할 수 있습니다.


// =====================================================
// 19단계. 브라우저 탭 활성화 감지
// =====================================================
// 네 번째 useEffect에서는 visibilitychange 이벤트를 등록합니다.
//
// visibilitychange는 브라우저 문서의
// 표시 상태가 변경될 때 발생하는 이벤트입니다.
//
// document.hidden을 이용하여
// 현재 문서가 숨겨져 있는지 확인합니다.
//
// document.hidden이 false이면
// 사용자가 문서를 다시 볼 수 있는 상태입니다.
//
// 이때 setUnreadCount(0)을 실행합니다.
//
// 읽지 않은 알림 개수를 초기화합니다.


// =====================================================
// 20단계. visibilitychange 이벤트 정리
// =====================================================
// document.addEventListener()로
// visibilitychange 이벤트를 등록합니다.
//
// 컴포넌트가 종료되면
// removeEventListener()로 이벤트를 제거합니다.
//
// 이를 통해 불필요한 이벤트 실행을 방지합니다.
//
// 참고로 이 예제는 브라우저 탭의 표시 상태를 확인합니다.
//
// 사용자가 실제로 메시지를 읽었는지까지
// 추적하는 기능은 포함되어 있지 않습니다.


// =====================================================
// 21단계. 자동 응답 타이머 정리
// =====================================================
// 다섯 번째 useEffect는 컴포넌트 종료 시
// 남아 있는 자동 응답 타이머를 정리합니다.
//
// replyTimersRef.current에 저장된 타이머를 가져옵니다.
//
// forEach()로 각 타이머를 반복합니다.
//
// clearTimeout(timer)으로 예약된 응답을 취소합니다.
//
// timers.clear()로 Set에 저장된 값도 비웁니다.
//
// 컴포넌트가 사라진 후
// 오래된 자동 응답이 실행되는 것을 방지합니다.


// =====================================================
// 22단계. 자동 응답 함수 생성
// =====================================================
// getAutoReply는 사용자가 보낸 메시지에 따라
// 자동 응답 문자열을 반환하는 함수입니다.
//
// userText를 전달받습니다.
//
