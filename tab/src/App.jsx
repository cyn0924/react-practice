// React 라이브러리와 상태관리를 위한 useState Hook을 불러옵니다.
// React는 JSX 문법을 해석하고 컴포넌트를 만들기 위해 필요합니다.
// useState는 현재 어떤 탭이 선택되어 있는지 저장하고 변경할 때 사용합니다.
import React, { useState } from "react";
import "./App.css";

// 재사용 가능한 탭 버튼 컴포넌트를 선언합니다
// label은 버튼에 표시할 글자
// isActive는 현재 선택된 탭인지 여부
// onClick은 버튼 클릭시 실행할 함수입니다.
function TabButton({ label, isActive, onClick }) {

  // TabButton 컴포넌트가 렌더링할 JSX를 반환합니다.
  return (

    // 버튼 요소
    <button

      // 버튼을 클릭했을 때 전달받은 onClick 함수를 실행합니다.
      onClick={onClick}

      // 현재 선택된 탭이면 active 클래스를 추가하고
      // 아니면 기본 tabButton 클래스를 적용합니다.
      className={`tabButton ${isActive ? "active" : ""}`}
    >

      {/* 버튼에 표시할 텍스트입니다. */}
      {label}
    </button>
  );
}

// 전체 탭 UI 기능을 담당하는 App 컴포넌트를 선언합니다.
function App() {

  // 현재 선택된 탭의 key를 저장하는 상태입니다.
  // 처음에는 html 탭이 선택된 상태로 시작합니다.
  const [activeTab, setActiveTab] = useState("html");

  // 각 탭별로 보여줄 데이터를 객체 형태로 정리합니다.
  // key는 탭 식별값이고 value는 title, description, content 배열을 가진 객체입니다.
  const tabData = {
    html: {

      // 화면에 표시할 탭 제목입니다.
      title: "HTML",

      // 해당탭에 대한 설명
      description: "웹 구조를 만드는 마크업 언어",

      // 리스트 형태로 보여줄 핵심 내용 배열입니다.
      content: [
        "웹 페이지 구조 구성",
        "태그 기반 구성",
        "JSX 이해에 필수",
      ],
    },
    css: {
      title: "CSS",
      description: "스타일을 담당하는 언어",
      content: [
        "색상, 레이아웃 조정",
        "반응형 UI 구현",
        "디자인 핵심 요소",
      ],
    },
    javascript: {
      title: "JavaScript",
      description: "동작을 만드는 언어",
      content: [
        "이벤트 처리",
        "데이터 처리",
        "비동기 로직",
      ],
    },
    react: {
      title: "React",
      description: "컴포넌트 기반 UI 라이브러리",
      content: [
        "재사용 컴포넌트",
        "state 관리",
        "SPA 구현",
      ],
    },
  };

  // 현재 activeTab 상태값에 해당하는 데이터를 tabData 객체에서 꺼내 currentTab에 저장합니다.
  // 예를 들어 activeTab이 "css"이면 tabData.css 객체가 들어갑니다.
  const currentTab = tabData[activeTab];

  // App 컴포넌트가 화면에 렌더링할 JSX 구조를 반환합니다.
  return (

    // 전체 탭 UI 화면을 감싸는 최상위 컨테이너입니다.
    <div className="container">

      {/* 상단 제목 */}
      <h1 className="title">탭 UI</h1>

      {/* 설명 문구 */}
      <p className="description">
        탭을 클릭하면 내용이 변경됩니다.
      </p>

      {/* 여러 개의 탭 버튼을 가로로 묶어 보여주는 영역입니다. */}
      <div className="tabWrap">

        {/* HTML 탭 버튼 */}
        <TabButton

          // 버튼에 표시할 글자
          label="HTML"

          // 현재 activeTab이 html이면 이 버튼을 활성 상태로 표시합니다.
          isActive={activeTab === "html"}

          // 클릭시 activeTab 상태를 html로 변경합니다.
          onClick={() => setActiveTab("html")}
        />

        <TabButton
          label="CSS"
          isActive={activeTab === "css"}
          onClick={() => setActiveTab("css")}
        />

        <TabButton
          label="JavaScript"
          isActive={activeTab === "javascript"}
          onClick={() => setActiveTab("javascript")}
        />

        <TabButton
          label="React"
          isActive={activeTab === "react"}
          onClick={() => setActiveTab("react")}
        />
      </div>

      {/* 현재 선택된 탭의 상세 내용을 보여주는 영역입니다. */}
      <div className="contentBox">

        {/* 현재 선택된 탭의 제목을 표시합니다. */}
        <h2 className="contentTitle">{currentTab.title}</h2>

        {/* 현재 선택된 탭의 설명을 표시합니다. */}
        <p className="contentDescription">
          {currentTab.description}
        </p>

        {/* 현재 선택된 탭의 핵심 내용들을 리스트 형태로 출력합니다. */}
        <ul className="list">

          {/* currentTab.content 배열을 순회하면서 li를 하나씩 만듭니다. */}
          {currentTab.content.map((item, index) => (
            <li key={index} className="listItem">

              {/* 배열의 각 문자열 내용을 화면에 표시합니다. */}
              {item}
            </li>
          ))}
        </ul>
      </div>
    </div>
  );
}

export default App;



 // =====================================================
 // React 탭 UI 시스템 전체 실행 흐름
 // =====================================================
 // 1. React와 useState를 불러옵니다.
 // 2. 재사용 가능한 TabButton 컴포넌트를 만듭니다.
 // 3. App 컴포넌트에서 현재 선택된 탭을 관리합니다.
 // 4. HTML, CSS, JavaScript, React 탭 데이터를 준비합니다.
 // 5. 현재 선택된 탭에 해당하는 데이터를 가져옵니다.
 // 6. 사용자가 탭 버튼을 클릭합니다.
 // 7. 클릭한 탭의 값을 activeTab에 저장합니다.
 // 8. React가 변경된 상태를 기준으로 화면을 다시 렌더링합니다.
 // 9. 선택된 탭 버튼에 active 클래스를 적용합니다.
 // 10. 해당 탭의 제목과 설명을 화면에 표시합니다.
 // 11. 탭의 주요 내용을 리스트 형태로 출력합니다.
 // 12. 다른 탭을 클릭하면 내용이 자동으로 변경됩니다.
 // =====================================================


 // =====================================================
 // 1단계. React 기능 및 CSS 불러오기
 // =====================================================
 // React는 컴포넌트를 생성하기 위해 사용합니다.
 // useState는 현재 선택된 탭을 상태로 관리합니다.
 // App.css는 탭 버튼과 콘텐츠 영역의 디자인을 담당합니다.


 // =====================================================
 // 2단계. 공통 TabButton 컴포넌트 생성
 // =====================================================
 // TabButton은 여러 탭에서 재사용하는 버튼 컴포넌트입니다.
 //
 // 부모 App 컴포넌트에서 다음 props를 전달받습니다.
 //
 // label    → 버튼에 표시할 이름
 // isActive → 현재 선택된 탭인지 확인하는 값
 // onClick  → 탭을 클릭했을 때 실행할 함수
 //
 // 하나의 TabButton 컴포넌트로 여러 탭 버튼을 만듭니다.


 // =====================================================
 // 3단계. 탭 버튼 클릭 이벤트 처리
 // =====================================================
 // 사용자가 탭 버튼을 클릭하면 onClick 함수가 실행됩니다.
 //
 // 실행 흐름
 // 탭 버튼 클릭
 // → onClick 이벤트 발생
 // → 부모 App에서 전달한 함수 실행
 // → setActiveTab으로 상태 변경
 // → React 화면 자동 업데이트
 //
 // 버튼마다 서로 다른 탭 이름을 전달합니다.


 // =====================================================
 // 4단계. 선택된 탭 버튼 디자인 변경
 // =====================================================
 // isActive 값에 따라 CSS 클래스를 변경합니다.
 //
 // 모든 버튼에는 tabButton 클래스를 적용합니다.
 //
 // isActive가 true이면 active 클래스를 추가합니다.
 // isActive가 false이면 기본 스타일을 적용합니다.
 //
 // 예시
 // HTML 탭 선택 → HTML 버튼에 active 적용
 // CSS 탭 선택 → CSS 버튼에 active 적용
 //
 // 선택된 탭을 시각적으로 구분할 수 있습니다.


 // =====================================================
 // 5단계. App 컴포넌트 생성
 // =====================================================
 // App은 전체 탭 UI 시스템을 관리하는 부모 컴포넌트입니다.
 //
 // 주요 역할
 // 현재 선택된 탭 관리
 // 탭별 데이터 관리
 // 탭 버튼 생성
 // 선택된 탭 데이터 가져오기
 // 탭 제목과 설명 표시
 // 탭 콘텐츠 리스트 출력
 //
 // TabButton 컴포넌트를 재사용하여 화면을 구성합니다.


 // =====================================================
 // 6단계. 현재 선택된 탭 상태 관리
 // =====================================================
 // activeTab은 현재 선택된 탭의 이름을 저장합니다.
 //
 // useState("html")로 초기값을 설정합니다.
 //
 // 따라서 처음 실행하면 HTML 탭이 선택됩니다.
 //
 // 저장 가능한 값
 // html
 // css
 // javascript
 // react
 //
 // 사용자가 다른 탭을 클릭하면 activeTab 값이 변경됩니다.


 // =====================================================
 // 7단계. 탭별 데이터 객체 준비
 // =====================================================
 // tabData 객체에 각 탭의 정보를 저장합니다.
 //
 // 각 탭에는 다음 데이터가 있습니다.
 //
 // title       → 탭 콘텐츠 제목
 // description → 탭에 대한 설명
 // content     → 주요 학습 내용 배열
 //
 // 탭마다 동일한 데이터 구조를 사용합니다.
 //
 // 이를 통해 탭별 화면을 따로 만들지 않고
 // 하나의 콘텐츠 영역에서 내용을 변경할 수 있습니다.


 // =====================================================
 // 8단계. HTML 탭 데이터 설정
 // =====================================================
 // html은 HTML 탭을 선택했을 때 표시할 데이터입니다.
 //
 // 제목: HTML
 // 설명: 웹 구조를 만드는 마크업 언어
 //
 // 주요 내용
 // 웹 페이지 구조 구성
 // 태그 기반 구성
 // JSX 이해에 필수
 //
 // 처음 실행하면 이 데이터가 화면에 표시됩니다.


 // =====================================================
 // 9단계. CSS 탭 데이터 설정
 // =====================================================
 // css는 CSS 탭을 선택했을 때 표시할 데이터입니다.
 //
 // 제목: CSS
 // 설명: 스타일을 담당하는 언어
 //
 // 주요 내용
 // 색상, 레이아웃 조정
 // 반응형 UI 구현
 // 디자인 핵심 요소
 //
 // CSS 버튼을 클릭하면 이 내용으로 변경됩니다.


 // =====================================================
 // 10단계. JavaScript 탭 데이터 설정
 // =====================================================
 // javascript는 JavaScript 탭의 데이터입니다.
 //
 // 제목: JavaScript
 // 설명: 동작을 만드는 언어
 //
 // 주요 내용
 // 이벤트 처리
 // 데이터 처리
 // 비동기 로직
 //
 // JavaScript 버튼을 클릭하면 이 내용이 표시됩니다.


 // =====================================================
 // 11단계. React 탭 데이터 설정
 // =====================================================
 // react는 React 탭을 선택했을 때 표시할 데이터입니다.
 //
 // 제목: React
 // 설명: 컴포넌트 기반 UI 라이브러리
 //
 // 주요 내용
 // 재사용 컴포넌트
 // state 관리
 // SPA 구현
 //
 // React 버튼을 클릭하면 이 내용으로 변경됩니다.


 // =====================================================
 // 12단계. 현재 선택된 탭 데이터 가져오기
 // =====================================================
 // currentTab은 현재 선택된 탭의 데이터를 저장합니다.
 //
 // tabData[activeTab]을 이용하여 데이터를 가져옵니다.
 //
 // 예시
 // activeTab이 "html"이면 tabData.html
 // activeTab이 "css"이면 tabData.css
 // activeTab이 "react"이면 tabData.react
 //
 // activeTab이 변경되면 currentTab도 새 값으로 계산됩니다.
 //
 // 현재 선택된 탭의 정보만 콘텐츠 영역에 표시합니다.


 // =====================================================
 // 13단계. JSX 전체 화면 구성
 // =====================================================
 // return에서 사용자가 보는 탭 UI 화면을 만듭니다.
 //
 // 화면 구성
 // 1. 탭 UI 제목
 // 2. 탭 기능 설명
 // 3. HTML 탭 버튼
 // 4. CSS 탭 버튼
 // 5. JavaScript 탭 버튼
 // 6. React 탭 버튼
 // 7. 선택된 탭의 콘텐츠 영역
 //
 // 탭이 변경되면 콘텐츠 영역이 자동 업데이트됩니다.


 // =====================================================
 // 14단계. 탭 버튼 영역 구성
 // =====================================================
 // tabWrap은 여러 탭 버튼을 감싸는 영역입니다.
 //
 // TabButton 컴포넌트를 4번 재사용합니다.
 //
 // HTML 버튼
 // CSS 버튼
 // JavaScript 버튼
 // React 버튼
 //
 // 버튼마다 다른 label과 onClick 함수를 전달합니다.
 //
 // 동일한 컴포넌트를 재사용하므로
 // 버튼 디자인과 동작을 일관되게 유지할 수 있습니다.


 // =====================================================
 // 15단계. 각 탭 버튼의 클릭 처리
 // =====================================================
 // HTML 버튼 클릭 → setActiveTab("html")
 // CSS 버튼 클릭 → setActiveTab("css")
 // JavaScript 버튼 클릭 → setActiveTab("javascript")
 // React 버튼 클릭 → setActiveTab("react")
 //
 // 클릭한 탭의 이름이 activeTab 상태에 저장됩니다.
 //
 // activeTab과 버튼의 탭 이름이 같으면
 // 해당 버튼의 isActive가 true가 됩니다.
 //
 // 따라서 한 번에 하나의 탭만 활성화됩니다.


 // =====================================================
 // 16단계. 선택된 탭 콘텐츠 영역 구성
 // =====================================================
 // contentBox는 선택한 탭의 정보를 표시하는 영역입니다.
 //
 // 콘텐츠 영역에는 다음 정보가 있습니다.
 //
 // 선택된 탭의 제목
 // 선택된 탭의 설명
 // 선택된 탭의 주요 내용 목록
 //
 // 탭을 변경해도 contentBox 자체의 구조는 유지됩니다.
 // 내부 데이터만 새로운 탭 정보로 변경됩니다.


 // =====================================================
 // 17단계. 탭 제목 및 설명 출력
 // =====================================================
 // currentTab.title은 선택된 탭의 제목을 표시합니다.
 // currentTab.description은 해당 탭의 설명을 표시합니다.
 //
 // 예시
 // HTML 탭 선택
 // → 제목: HTML
 // → 설명: 웹 구조를 만드는 마크업 언어
 //
 // React 탭 선택
 // → 제목: React
 // → 설명: 컴포넌트 기반 UI 라이브러리
 //
 // activeTab이 변경되면 제목과 설명도 자동 변경됩니다.


 // =====================================================
 // 18단계. 탭 콘텐츠 리스트 반복 출력
 // =====================================================
 // currentTab.content 배열을 map으로 반복 출력합니다.
 //
 // 배열에 저장된 문자열 하나마다 li 요소를 생성합니다.
 //
 // 예시: HTML 탭
 // 웹 페이지 구조 구성
 // 태그 기반 구성
 // JSX 이해에 필수
 //
 // 각 li에는 listItem 클래스를 적용합니다.
 // key에는 배열의 index 값을 사용합니다.
 //
 // 이 예제는 순서가 고정된 간단한 목록이므로
 // index를 key로 사용할 수 있습니다.


 // =====================================================
 // 19단계. React 상태 변경과 화면 업데이트
 // =====================================================
 // 사용자가 CSS 탭을 클릭했다고 가정합니다.
 //
 // CSS 버튼 클릭
 // → onClick 함수 실행
 // → setActiveTab("css") 실행
 // → activeTab 상태가 "css"로 변경
 // → React가 App 컴포넌트 재렌더링
 // → currentTab이 tabData.css를 참조
 // → CSS 버튼에 active 클래스 적용
 // → 제목과 설명이 CSS 내용으로 변경
 // → CSS 주요 학습 내용 리스트 출력
 //
 // 별도의 페이지 이동이나 새로고침 없이
 // 화면의 콘텐츠가 자동으로 변경됩니다.


 // =====================================================
 // 20단계. 컴포넌트 재사용 구조 이해
 // =====================================================
 // TabButton은 탭 버튼의 화면과 동작을 담당합니다.
 // App은 현재 선택된 탭과 전체 데이터를 관리합니다.
 //
 // 부모 App에서 자식 TabButton으로
 // label, isActive, onClick을 전달합니다.
 //
 // 자식 TabButton에서 클릭 이벤트가 발생하면
 // 부모에서 전달한 onClick 함수가 실행됩니다.
 //
 // 부모의 activeTab 상태가 변경되면
 // 자식 버튼의 활성화 여부도 다시 계산됩니다.
 //
 // 이것이 React의 단방향 데이터 흐름입니다.


 // =====================================================
 // 최종 실행 결과
 // =====================================================
 // 1. HTML, CSS, JavaScript, React 탭을 표시합니다.
 // 2. 처음에는 HTML 탭이 선택되어 있습니다.
 // 3. 탭 버튼을 클릭하면 선택한 탭이 활성화됩니다.
 // 4. 활성화된 탭에는 active 클래스를 적용합니다.
 // 5. 탭별 제목과 설명을 다르게 표시합니다.
 // 6. 탭별 주요 학습 내용을 리스트로 출력합니다.
 // 7. 다른 탭을 클릭하면 콘텐츠가 자동 변경됩니다.
 // 8. 한 번에 하나의 탭만 활성화됩니다.
 // 9. 하나의 TabButton 컴포넌트를 반복해서 사용합니다.
 // 10. React 상태 변경으로 페이지 새로고침 없이 작동합니다.


 // =====================================================
 // 핵심 학습 내용
 // =====================================================
 // useState → 현재 선택된 탭 상태 관리
 // props → 부모에서 자식 컴포넌트로 데이터 전달
 // TabButton → 재사용 가능한 탭 버튼 컴포넌트
 // activeTab → 현재 선택된 탭 이름
 // setActiveTab → 선택된 탭 변경
 // tabData → 탭별 콘텐츠 데이터 관리
 // currentTab → 현재 선택된 탭 데이터
 // onClick → 탭 버튼 클릭 이벤트 처리
 // isActive → 현재 버튼의 활성화 여부 확인
 // className → 활성화된 탭의 CSS 스타일 적용
 // 삼항 연산자 → active 클래스 적용 여부 결정
 // map → 탭 콘텐츠 리스트 반복 출력
 // key → React가 리스트 항목을 구분
 // 객체 속성 접근 → tabData[activeTab]으로 데이터 선택
 // 컴포넌트 재사용 → 하나의 TabButton으로 여러 탭 생성
 // 단방향 데이터 흐름 → 부모 상태를 자식 컴포넌트에 전달


 // =====================================================
 // 가장 중요한 React 탭 UI 작동 원리
 // =====================================================
 // 사용자가 탭 버튼 클릭
 // → onClick 이벤트 발생
 // → setActiveTab 함수 실행
 // → activeTab 상태 변경
 // → React가 App 컴포넌트 재렌더링
 // → tabData[activeTab]으로 현재 탭 데이터 선택
 // → currentTab 값 변경
 // → 선택된 탭 버튼에 active 클래스 적용
 // → 콘텐츠 제목과 설명 변경
 // → 주요 학습 내용 리스트 업데이트
 //
 // 핵심: 하나의 공통 탭 버튼 컴포넌트를 재사용하고
 // useState로 현재 선택된 탭을 관리하면
 // 페이지 이동 없이 다양한 콘텐츠를 전환할 수 있습니다.
 // =====================================================
