// 전체 화면과 메뉴 상태를 관리하는 App 컴포넌트를 선언합니다.
function App() {
  
  // 현재 선택된 탭의 이름을 저장합니다.
  // 처음에는 홈 탭이 선택되도록 "home" 으로 시작합니다.
  const [activeTab, setActiveTab] = useState("home");

  // 현재 선택된 탭에 맞는 페이지 컴포넌트를 반환하는 함수입니다.
  const renderPage = () => {
    if (activeTab === "home") {
      return <HomePage />;
    }

    if (activeTab === "about") {
      return <AboutPage />;
    }

    if (activeTab === "profile") {
      return <ProfilePage />;
    }

    return <HomePage />;
  };

  // 화면에 렌더링할 JSX를 반환합니다.
  return (

    // 전체 페이지를 감싸는 최상위 영역입니다.
    <div className="page">

      {/* 화면의 최대 너비와 전체 레이아웃을 관리하는 컨테이너입니다. */}
      <div className="container">
        <h1 className="title">lazy loading 적용</h1>

        <p className="subtitle">
          React.lazy와 Suspense를 사용해서 컴포넌트를 필요할 때만
          불러오는 App.jsx 예제입니다.
        </p>

        {/* 메뉴 버튼을 감싸는 카드 영역입니다. */}
        <div className="top-card">

          {/* 메뉴 영역의 제목 */}
          <h2 className="section-title">메뉴</h2>

          {/* 탭 버튼을 배치하는 영역입니다. */}
          <div className="tab-row">
            <button
              type="button"

              // 현재 탭이 home이면 active 클래스를 추가합니다.
              className={`tab-button ${
                activeTab === "home" ? "active" : ""
              }`}

              // 클릭하면 activeTab을 home으로 변경합니다.
              onClick={() => setActiveTab("home")}
            >
              홈
            </button>

            <button
              type="button"
              className={`tab-button ${
                activeTab === "about" ? "active" : ""
              }`}
              onClick={() => setActiveTab("about")}
            >
              소개
            </button>

            <button
              type="button"
              className={`tab-button ${
                activeTab === "profile" ? "active" : ""
              }`}
              onClick={() => setActiveTab("profile")}
            >
              프로필
            </button>
          </div>
        </div>

        {/* 선택한 페이지 컴포넌트를 표시하는 카드 영역입니다. */}
        <div className="content-card">

          {/* 현재 영역의 제목을 표시합니다. */}
          <h2 className="section-title">지연 로딩 화면</h2>

          {/* lazy 컴포넌트가 로드되는 동안 보여줄 화면을 설정합니다. */}
          <Suspense

            // HomePage, AboutPage, ProfilePage를 불러오는 동안 표시할 로딩 UI입니다.
            fallback={

              // 로딩 상태를 보여주는 박스입니다.
              <div className="loading-box">

                {/* 회전하는 로딩 아이콘 영역입니다. */}
                <div className="spinner" />

                {/* 컴포넌트를 불러오는 중임을 안내합니다. */}
                <p className="loading-text">
                  컴포넌트를 불러오는 중입니다...
                </p>
              </div>
            }
          >

            {/* 현재 선택된 탭에 맞는 지연 로딩 페이지를 출력합니다. */}
            {renderPage()}
          </Suspense>
        </div>

        {/* React.lazy와 Suspense의 핵심 내용을 설명하는 카드입니다. */}
        <div className="bottom-card">
          <h2 className="section-title">핵심 포인트</h2>

          {/* 핵심 포인트 카드를 배치하는 영역 */}
          <div className="explain-grid">

            {/* React.lazy 설명 카드 */}
            <div className="explain-item">
              <strong>1. React.lazy</strong>
              <p className="explain-text">
                컴포넌트를 즉시 불러오지 않고, 실제로 렌더링이 필요할 때
                불러옵니다.
              </p>
            </div>

            {/* Suspense 설명 카드 */}
            <div className="explain-item">

              {/* 설명 제목 */}
              <strong>2. Suspense</strong>

              {/* Suspense의 역할을 설명 */}
              <p className="explain-text">
                lazy 컴포넌트가 로드되는 동안 보여줄 fallback UI를 설정합니다.
              </p>
            </div>

            {/* 코드 분할 설명 카드 */}
            <div className="explain-item">
              <strong>3. 코드 분할</strong>
              <p className="explain-text">
                큰 페이지나 무거운 기능을 나눠서 초기 렌더링 부담을 줄일 수
                있습니다.
              </p>
            </div>

            {/* 코드 분할의 장점 */}
            <div className="explain-item">
              <strong>4. 실무 사용</strong>
              <p className="explain-text">
                보통 라우트 페이지, 대시보드, 차트 컴포넌트, 관리자 화면 등에
                많이 사용합니다.
              </p>
            </div>
          </div>
        </div>

        {/* 실무에서 사용하는 lazy loading 코드 예시를 보여주는 영역 */}
        <div className="code-card">
          <h2 className="section-title">
            실무에서 자주 쓰는 형태
          </h2>

          <pre className="code-box">
            {`const HomePage = lazy(() => import("./pages/HomePage"));

<Suspense fallback={<div>Loading...</div>}>
  <HomePage />
</Suspense>`}
          </pre>
        </div>
      </div>
    </div>
  );
}

export default App;



