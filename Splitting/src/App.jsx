// 여러 지연 로딩 페이지를 관리하는 최상위 App 컴포넌트입니다.
function App() {

  // 현재 선택된 페이지 이름을 저장합니다.
  // 처음에는 대시보드가 보이도록 dashboard로 시작합니다.
  const [activePage, setActivePage] = useState("dashboard");

  // 현재 선택된 메뉴에 맞는 페이지 컴포넌트를 반환하는 함수입니다.
  const renderPage = () => {
    if (activePage === "dashboard") return <DashboardPage />;

    if (activePage === "chart") return <ChartPage />;

    if (activePage === "settings") return <SettingsPage />;

    if (activePage === "profile") return <ProfilePage />;

    // 예상하지 못한 값이 들어오면 대시보드를 기본 화면으로 보여줍니다.
    return <DashboardPage />;
  };

  // 화면에 렌더링할 JSX를 반환합니다.
  return (

    // 전체 페이지를 감싸는 최상위 영역입니다.
    <div className="page">

      {/* 페이지의 최대 너비와 전체 콘텐츠 배치를 담당하는 영역입니다. */}
      <div className="container">
        <h1 className="title">코드 스플리팅 구현</h1>

        <p className="subtitle">
          React.lazy와 Suspense를 사용해서 페이지 단위로 코드를 분리하고,
          필요한 순간에만 로드하는 App.jsx 예제입니다.
        </p>

        {/* 메뉴 버튼을 배치하는 카드 영역입니다. */}
        <div className="top-card">
          <h2 className="section-title">메뉴</h2>

          <div className="menu-row">
            <button
              type="button"

              // 클릭하면 activePage를 dashboard로 변경합니다.
              onClick={() => setActivePage("dashboard")}

              // 현재 대시보드가 선택되어 있으면 active 클래스를 추가합니다.
              className={`menu-button ${
                activePage === "dashboard" ? "active" : ""
              }`}
            >
              대시보드
            </button>

            <button
              type="button"

              // 클릭하면 activePage를 chart로 변경해서 차트 분석페이지로 이동합니다.
              onClick={() => setActivePage("chart")}

              // 현재 차트 페이지가 선택되어 있으면 active 클래스를 추가합니다.
              className={`menu-button ${
                activePage === "chart" ? "active" : ""
              }`}
            >
              차트 분석
            </button>

            <button
              type="button"

              // 클릭하면 activePage를 settings로 변경해서 설정 페이지로 이동합니다.
              onClick={() => setActivePage("settings")}

              // 현재 설정 페이지가 선택되어 active 클래스를 추가합니다.
              className={`menu-button ${
                activePage === "settings" ? "active" : ""
              }`}
            >
              설정
            </button>

            <button
              type="button"

              // 클릭하면 activePage를 profile로 변경합니다.
              onClick={() => setActivePage("profile")}

              // 현재 프로필 페이지가 선택되어 있으면 active 클래스를 추가합니다.
              className={`menu-button ${
                activePage === "profile" ? "active" : ""
              }`}
            >
              프로필
            </button>
          </div>
        </div>

        {/* 현재 선택된 지연 로딩 페이지를 표시하는 영역입니다. */}
        <div className="content-card">
          <h2 className="section-title">분리된 페이지 영역</h2>

          {/* lazy 컴포넌트가 로드되는 동안 fallback 화면을 보여줍니다. */}
          <Suspense

            // 페이지 코드가 아직 불러와지지 않았을 때 표시할 로딩 UI 입니다.
            fallback={

              // 로딩 화면을 감싸는 영역입니다.
              <div className="loading-box">

                {/* CSS 애니메이션이 적용될 로딩 스피너입니다. */}
                <div className="spinner" />
                <p className="loading-text">
                  페이지 코드를 불러오는 중입니다...
                </p>
              </div>
            }
          >
            {/* activePage 값에 맞는 페이지 컴포넌트를 출력합니다. */}
            {renderPage()}
          </Suspense>
        </div>

        {/* 코드 스플리팅의 주요 개념을 설명하는 카드입니다. */}
        <div className="bottom-card">
          <h2 className="section-title">코드 스플리팅 핵심</h2>

          {/* 설명 카드를 배치하는 영역입니다. */}
          <div className="explain-grid">

            {/* 설명 */}
            <div className="explain-item">
              <strong>1. 초기 번들 감소</strong>
              <p className="explain-text">
                처음부터 모든 페이지를 한 번에 불러오지 않아서 초기 로딩이 더
                가벼워집니다.
              </p>
            </div>

            <div className="explain-item">
              <strong>2. 페이지 단위 분리</strong>
              <p className="explain-text">
                라우트 페이지, 차트, 관리자 화면처럼 큰 단위를 나누기에 좋습니다.
              </p>
            </div>

            <div className="explain-item">
              <strong>3. Suspense fallback</strong>
              <p className="explain-text">
                아직 로드되지 않은 동안 사용자에게 로딩 UI를 보여줄 수 있습니다.
              </p>
            </div>

            <div className="explain-item">
              <strong>4. 실무 활용</strong>
              <p className="explain-text">
                보통 pages, routes, charts, modal 내부 무거운 컴포넌트에 많이
                적용합니다.
              </p>
            </div>
          </div>
        </div>

        {/* 코드 작성 방법을 보여주는 영역 */}
        <div className="code-card">
          <h2 className="section-title">실무에서 자주 쓰는 형태</h2>

          <pre className="code-box">
            {`import React, { lazy, Suspense } from "react";

const DashboardPage = lazy(() => import("./pages/DashboardPage"));
const ChartPage = lazy(() => import("./pages/ChartPage"));

function App() {
  return (
    <Suspense fallback={<div>Loading...</div>}>
      <DashboardPage />
    </Suspense>
  );
}`}
          </pre>
        </div>
      </div>
    </div>
  );
}

export default App;


// =====================================================
// React 코드 스플리팅 시스템 전체 실행 흐름
// =====================================================
// 1. React와 Suspense, lazy, useState를 불러옵니다.
// 2. React.lazy로 대시보드 페이지를 정의합니다.
// 3. React.lazy로 차트 분석 페이지를 정의합니다.
// 4. React.lazy로 설정 페이지를 정의합니다.
// 5. React.lazy로 프로필 페이지를 정의합니다.
// 6. App 컴포넌트에서 현재 선택된 페이지를 관리합니다.
// 7. 처음 실행하면 대시보드 페이지를 표시합니다.
// 8. 사용자가 메뉴 버튼을 클릭합니다.
// 9. 클릭한 메뉴에 따라 activePage 상태를 변경합니다.
// 10. renderPage 함수로 표시할 컴포넌트를 선택합니다.
// 11. Suspense가 컴포넌트의 로딩 상태를 처리합니다.
// 12. 필요한 경우 fallback 로딩 화면을 표시합니다.
// 13. 컴포넌트가 준비되면 실제 페이지를 표시합니다.
// 14. 선택된 메뉴에 active 클래스를 적용합니다.
// 15. 다른 메뉴를 선택하면 해당 페이지로 전환합니다.
// 16. React 상태 변경에 따라 화면이 자동 업데이트됩니다.
// =====================================================


// =====================================================
// 1단계. React 기능 및 CSS 불러오기
// =====================================================
// React는 사용자 인터페이스를 만들기 위해 사용합니다.
//
// Suspense는 컴포넌트가 준비되기 전
// 사용자에게 표시할 로딩 화면을 설정합니다.
//
// lazy는 컴포넌트를 필요한 시점에 불러오도록 정의합니다.
//
// useState는 현재 선택된 페이지를 관리합니다.
//
// App.css는 메뉴 버튼, 페이지 카드,
// 차트, 프로필, 로딩 화면 등의 디자인을 담당합니다.


// =====================================================
// 2단계. 코드 스플리팅이란?
// =====================================================
// 코드 스플리팅은 JavaScript 코드를
// 여러 개의 파일로 나누는 기술입니다.
//
// 일반적인 방식
// → 여러 페이지의 코드를 처음부터 함께 불러옵니다.
//
// 코드 스플리팅 방식
// → 처음 필요한 코드부터 불러옵니다.
// → 나머지 코드는 필요한 시점에 불러올 수 있습니다.
//
// 이를 통해 초기 JavaScript 다운로드 크기를
// 줄이는 데 도움을 줄 수 있습니다.
//
// 실제 코드 분할에는 일반적으로
// import()와 Vite 같은 빌드 도구를 사용합니다.


// =====================================================
// 3단계. React.lazy의 역할
// =====================================================
// React.lazy는 컴포넌트의 로딩을 지연시키는 기능입니다.
//
// lazy에는 Promise를 반환하는 함수를 전달합니다.
//
// Promise의 결과에는
// default 속성으로 React 컴포넌트가 들어 있어야 합니다.
//
// 예시
// const DashboardPage = lazy(() =>
//   import("./pages/DashboardPage")
// );
//
// 이 형태를 사용하면 DashboardPage를
// 별도의 JavaScript 청크로 분리할 수 있습니다.


// =====================================================
// 4단계. Promise.resolve의 역할
// =====================================================
// 현재 예제에서는 import() 대신
// Promise.resolve()를 사용합니다.
//
// Promise.resolve()는 전달한 값을
// 이행된 Promise로 만들어 반환합니다.
//
// default 속성에는 페이지 컴포넌트를 저장합니다.
//
// React.lazy는 반환된 Promise를 통해
// 해당 컴포넌트를 렌더링할 수 있습니다.
//
// 하지만 현재 코드의 페이지 컴포넌트들은
// 모두 같은 App.jsx 파일 안에 작성되어 있습니다.
//
// 따라서 이 예제 자체는 실제 파일 단위의
// 코드 스플리팅을 구현하지 않습니다.


// =====================================================
// 5단계. DashboardPage 컴포넌트 정의
// =====================================================
// DashboardPage는 대시보드 메뉴의 화면입니다.
//
// React.lazy로 컴포넌트를 정의합니다.
//
// 화면 구성
// 대시보드 제목
// 페이지 설명
// 방문자 수 카드
// 오늘 매출 카드
// 신규 가입 카드
//
