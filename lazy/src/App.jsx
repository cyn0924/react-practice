// React에서 비동기 컴포넌트 로딩과 상태 관리를 위한 기능을 가져옵니다.
// Suspense는 지연로딩 중에 보여줄 화면을 설정할 때 사용합니다.
// lazy는 컴포넌트를 필요한 순간에 불러올 때 사용합니다.
// useState는 현재 선택된 메뉴를 저장할 때 사용합니다.
// lazy Loading은 지연 로딩 이라는 뜻
// 처음부터 모든 데이터를 불러오지 않고 필요한 순간에 불러오는 기술입니다.
// 지금 당장 사용하지 않는 페이지나 컴포넌트는 나중에 불러오는 방식입니다.
import React, { Suspense, lazy, useState } from "react";
import "./App.css";

