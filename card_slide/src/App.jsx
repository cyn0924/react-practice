// React 라이브러리에서 컴포넌트 상태를 관리할 수 있는 useState Hook을 가져옵니다.
import React, { useState } from "react";
import "./App.css";

// 카드 슬라이드 화면 전체를 담당하는 App 컴포넌트를 선언합니다.
function App() {

  // 슬라이드에 사용할 카드 데이터를 배열로 저장합니다.
  // 각각의 카드에는 번호, 제목, 설명, 카테고리, 이미지 주소가 포함되어 있습니다.
  const cards = [
    {

      // 각 카드를 구분하기 위한 고유 번호입니다.
      id: 1,

      // 제목
      title: "React 기초",

      // 설명
      desc: "컴포넌트, props, state를 배우는 단계",

      // 카테고리
      category: "프론트엔드",

      // 이미지 주소
      image: "https://picsum.photos/400/300?random=1",
    },
    {
      id: 2,
      title: "JavaScript 심화",
      desc: "비동기 처리와 함수형 프로그래밍 이해",
      category: "자바스크립트",
      image: "https://picsum.photos/400/300?random=2",
    },
    {
      id: 3,
      title: "UX/UI 디자인",
      desc: "사용자 경험을 고려한 디자인 설계",
      category: "디자인",
      image: "https://picsum.photos/400/300?random=3",
    },
    {
      id: 4,
      title: "백엔드 입문",
      desc: "서버와 API 구조 이해하기",
      category: "백엔드",
      image: "https://picsum.photos/400/300?random=4",
    },
    {
      id: 5,
      title: "데이터베이스",
      desc: "SQL과 데이터 구조 학습",
      category: "DB",
      image: "https://picsum.photos/400/300?random=5",
    },
    {
      id: 6,
      title: "포트폴리오 제작",
      desc: "실전 프로젝트 만들기",
      category: "프로젝트",
      image: "https://picsum.photos/400/300?random=6",
    },
  ];

  // 현재 화면에 표시할 카드의 배열 위치를 저장합니다.
  // 인덱스번호 0은 첫번째 카드를 의미하며 인덱스번호 1은 두번째 카드를 의미한다.
  const [currentIndex, setCurrentIndex] = useState(0);

  // 이전 슬라이드 버튼을 클릭했을 때 실행되는 함수입니다.
  const prevSlide = () => {

    // 첫 번째 카드에서 이전 버튼을 누르면 마지막 카드로 이동합니다.
    setCurrentIndex((prev) => prev === 0 ? cards.length - 1 : prev - 1);
  };

  // 다음 슬라이드 버튼을 클릭했을 때 실행되는 함수입니다.
  const nextSlide = () => {

    // 현재 인덱스 번호를 기준으로 다음 카드의 위치를 계산합니다.
    // 마지막 카드에서 다음 버튼을 누르면 첫 번째 카드로 이동합니다.
    setCurrentIndex((prev) => prev === cards.length - 1 ? 0 : prev + 1);
  };

  // 화면에 렌더링할 JSX를 반환합니다.
  return (

    // 카드 슬라이드 전체를 감싸는 영역입니다.
    <div className="container">

      {/*제목 */}
      <h1 className="title">카드 슬라이드 UI</h1>

      {/* 이전 버튼, 카드, 다음 버튼을 배치하는 슬라이드 영역입니다. */}
      <div className="sliderWrap">

        {/* 이전 카드로 이동하는 버튼입니다. */}
        <button className="arrow" onClick={prevSlide}>‹</button>

        {/* 현재 선택된 카드 하나를 표시합니다. */}
        <div className="card">

          {/* 카드 이미지와 카테고리 배치를 감사는 영역 */}
          <div className="imageWrap">

            {/* currentIndex에 해당하는 카드의 이미지를 출력합니다. */}
            {/* 이미지 경로와 이미지가 표시되지 않을 때 사용할 대체 설명입니다. */}
            <img src={cards[currentIndex].image} alt={cards[currentIndex].title}/>

            {/* 현재 카드의 카테고리를 배지 형태로 표시합니다. */}
            <span className="badge">{cards[currentIndex].category}</span>
          </div>

          {/* 카드의 제목, 설명, 버튼을 포함하는 내용영역입니다. */}
          <div className="content">

            {/* 현재 카드의 제목을 출력합니다. */}
            <h2 className="cardTitle">{cards[currentIndex].title}</h2>

            {/* 현재 카드의 설명을 출력합니다. */}
            <p className="desc">{cards[currentIndex].desc}</p>

            {/* 카드 하단의 버튼을 감싸는 영역입니다. */}
            <div className="footer">

              {/* 현재 카드의 상세 내용을 확인하는 버튼입니다. */}
              <button className="button">자세히 보기</button>
            </div>
          </div>
        </div>

        {/* 다음 카드로 이동하는 버튼입니다. */}
        <button className="arrow" onClick={nextSlide}>›</button>
      </div>

      {/* 현재 카드의 위치를 보여주는 점 네비게이션 영역입니다. */}
      {/* cards 배열의 개수만큼 점을 반복해서 생성합니다. */}
      <div className="dots">{cards.map((_, index) => (

        // 각 점을 구분하기 위한 key값으로 index를 사용합니다.
        <span
          key={index}

          // 점을 클릭하면 해당 순서의 카드로 이동합니다.
          onClick={() => setCurrentIndex(index)}

          // 현재 카드의 순서와 점의 순서가 같으면 active 클래스를 추가합니다.
          // active 클래스는 현재 선택된 점을 강조하는 CSS에 사용됩니다.
          className={`dot ${currentIndex === index ? "active" : ""}`}
        />
      ))}
      </div>
    </div>
  );
}

export default App;

// ==================================================================================
// React 카드 슬라이드 UI 전체 실행 흐름
// ==================================================================================
// 1. React와 UseState를 불러옵니다.
// 2. 카드 슬라이드에 사용할 데이터 6개를 준비합니다.
// 3. 각 카드의 제목, 설명, 카테고리, 이미지를 설정합니다.
// 4. 현재 화면에 표시할 카드의 인덱스를 상태로 관리합니다.
// 5. 처음 실행하면 첫 번째 카드를 표시합니다.
// 6. 이전 버튼을 클릭하면 이전 카드로 이동합니다.
// 7. 다음 버튼을 클릭하면 다음 카드로 이동합니다.
// 8. 첫 번째 카드에서 이전을 누르면 마지막 카드로 이동합니다.
// 9. 마지막 카드에서 다음을 누르면 첫 번째 카드로 이동합니다.
// 10. 현재 인덱스에 해당하는 카드 데이터를 화면에 표시합니다.
// 11. 카드 개수만큼 하단 페이지 표시 점을 생성합니다.
// 12. 현재 선택된 점에 active 클래스를 적용합니다. 
// 13. 점을 클릭하면 해당 순서의 카드로 바로 이동합니다. 
// 14. React 상태 변경에 따라 카드 내용이 자동 업데이트됩니다.
// ==================================================================================


 // =====================================================
 // 1단계. React 기능 및 CSS 불러오기
 // =====================================================
 // React는 컴포넌트를 생성하기 위해 사용합니다.
 // useState는 현재 표시 중인 카드의 인덱스를 관리합니다.
 // App.css는 카드, 슬라이드 버튼, 페이지 표시 점을 디자인합니다.


 // =====================================================
 // 2단계. App 컴포넌트 생성
 // =====================================================
 // App은 전체 카드 슬라이드 시스템을 관리합니다.
 //
 // 주요 역할
 // 카드 데이터 관리
 // 현재 카드 인덱스 관리
 // 이전 카드 이동
 // 다음 카드 이동
 // 카드 내용 표시
 // 하단 페이지 표시 점 생성
 // 점 클릭으로 원하는 카드 이동
 //
 // 하나의 상태값으로 전체 슬라이드 기능을 제어합니다.


 // =====================================================
 // 3단계. 카드 데이터 배열 준비
 // =====================================================
 // cards 배열에 총 6개의 카드 정보를 저장합니다.
 //
 // 각 카드에는 다음 정보가 있습니다.
 //
 // id       → 카드 고유번호
 // title    → 카드 제목
 // desc     → 카드 설명
 // category → 카드 카테고리
 // image    → 카드 이미지 주소
 //
 // 배열에 저장된 순서대로 슬라이드가 표시됩니다.
 // 각 카드의 데이터는 동일한 구조로 구성됩니다.


 // =====================================================
 // 4단계. 첫 번째 카드 데이터 설정
 // =====================================================
 // 첫 번째 카드는 React 기초 학습 내용입니다.
 //
 // 제목: React 기초
 // 설명: 컴포넌트, props, state를 배우는 단계
 // 카테고리: 프론트엔드
 //
 // 처음 실행하면 이 카드가 화면에 표시됩니다.


 // =====================================================
 // 5단계. 두 번째 카드 데이터 설정
 // =====================================================
 // 두 번째 카드는 JavaScript 심화 학습 내용입니다.
 //
 // 제목: JavaScript 심화
 // 설명: 비동기 처리와 함수형 프로그래밍 이해
 // 카테고리: 자바스크립트
 //
 // 첫 번째 카드에서 다음 버튼을 누르면 표시됩니다.


 // =====================================================
 // 6단계. 나머지 카드 데이터 설정
 // =====================================================
 // 세 번째 카드 → UI/UX 디자인
 // 네 번째 카드 → 백엔드 입문
 // 다섯 번째 카드 → 데이터베이스
 // 여섯 번째 카드 → 포트폴리오 제작
 //
 // 각 카드에는 이미지, 제목, 설명, 카테고리가 있습니다.
 // cards 배열에 새로운 객체를 추가하면
 // 슬라이드 카드와 하단 점 개수도 함께 늘어납니다.


 // =====================================================
 // 7단계. 현재 카드 인덱스 상태 관리
 // =====================================================
 // currentIndex는 현재 화면에 표시 중인 카드의 위치입니다.
 //
 // useState(0)으로 초기값을 설정합니다.
 //
 // 배열의 인덱스는 0부터 시작합니다.
 //
 // currentIndex = 0 → 첫 번째 카드
 // currentIndex = 1 → 두 번째 카드
 // currentIndex = 2 → 세 번째 카드
 // currentIndex = 5 → 여섯 번째 카드
 //
 // 현재 인덱스가 변경되면 표시되는 카드도 변경됩니다.


 // =====================================================
 // 8단계. 이전 카드 이동 함수 구현
 // =====================================================
 // prevSlide 함수는 이전 버튼을 클릭하면 실행됩니다.
 //
 // 실행 흐름
 // 이전 버튼 클릭
 // → prevSlide 함수 실행
 // → 현재 인덱스 확인
 // → 인덱스를 1 감소
 // → setCurrentIndex 실행
 // → 이전 카드 화면 표시
 //
 // 예시
 // 세 번째 카드 → 이전 클릭 → 두 번째 카드
 // 두 번째 카드 → 이전 클릭 → 첫 번째 카드


 // =====================================================
 // 9단계. 첫 번째 카드에서 이전 버튼 클릭 처리
 // =====================================================
 // currentIndex가 0인지 확인합니다.
 //
 // 현재 첫 번째 카드라면
 // cards.length - 1을 새로운 인덱스로 설정합니다.
 //
 // 카드가 6개이므로 마지막 인덱스는 5입니다.
 //
 // 예시
 // 첫 번째 카드 → 이전 클릭 → 여섯 번째 카드
 //
 // 이를 통해 슬라이드가 끊기지 않고 순환합니다.


 // =====================================================
 // 10단계. 다음 카드 이동 함수 구현
 // =====================================================
 // nextSlide 함수는 다음 버튼을 클릭하면 실행됩니다.
 //
 // 실행 흐름
 // 다음 버튼 클릭
 // → nextSlide 함수 실행
 // → 현재 인덱스 확인
 // → 인덱스를 1 증가
 // → setCurrentIndex 실행
 // → 다음 카드 화면 표시
 //
 // 예시
 // 첫 번째 카드 → 다음 클릭 → 두 번째 카드
 // 두 번째 카드 → 다음 클릭 → 세 번째 카드


 // =====================================================
 // 11단계. 마지막 카드에서 다음 버튼 클릭 처리
 // =====================================================
 // currentIndex가 cards.length - 1인지 확인합니다.
 //
 // 현재 마지막 카드라면
 // 새로운 인덱스를 0으로 설정합니다.
 //
 // 예시
 // 여섯 번째 카드 → 다음 클릭 → 첫 번째 카드
 //
 // 첫 번째 카드부터 다시 시작하는 순환형 슬라이드입니다.
 //
 // 이전과 다음 이동 모두 삼항 연산자로 처리합니다.


 // =====================================================
 // 12단계. JSX 전체 화면 구성
 // =====================================================
 // return에서 사용자가 보는 카드 슬라이드 화면을 만듭니다.
 //
 // 화면 구성
 // 1. 카드 슬라이드 UI 제목
 // 2. 이전 슬라이드 버튼
 // 3. 현재 카드 이미지
 // 4. 카테고리 배지
 // 5. 카드 제목
 // 6. 카드 설명
 // 7. 자세히 보기 버튼
 // 8. 다음 슬라이드 버튼
 // 9. 하단 페이지 표시 점
 //
 // currentIndex 상태에 따라 카드 내용이 변경됩니다.


 // =====================================================
 // 13단계. 이전 및 다음 버튼 영역 구성
 // =====================================================
 // sliderWrap은 카드와 양쪽 화살표 버튼을 감쌉니다.
 //
 // 왼쪽 버튼은 이전 카드로 이동합니다.
 // 오른쪽 버튼은 다음 카드로 이동합니다.
 //
 // 이전 버튼 → onClick={prevSlide}
 // 다음 버튼 → onClick={nextSlide}
 //
 // 버튼을 클릭하면 currentIndex가 변경됩니다.
 // 상태 변경 후 React가 화면을 다시 렌더링합니다.


 // =====================================================
 // 14단계. 현재 카드 이미지 표시
 // =====================================================
 // cards[currentIndex]로 현재 카드 데이터를 가져옵니다.
 //
 // image 속성을 img의 src에 연결합니다.
 // title 속성을 img의 alt에 연결합니다.
 //
 // 예시
 // currentIndex = 0 → React 기초 이미지
 // currentIndex = 1 → JavaScript 심화 이미지
 //
 // 인덱스가 변경되면 이미지도 자동으로 변경됩니다.
 //
 // 이미지 주소는 Picsum Photos 서비스를 사용합니다.


 // =====================================================
 // 15단계. 카드 카테고리 배지 표시
 // =====================================================
 // cards[currentIndex].category를 출력합니다.
 //
 // 카테고리는 이미지 영역 안에 배지 형태로 표시합니다.
 //
 // 예시
 // React 기초 → 프론트엔드
 // JavaScript 심화 → 자바스크립트
 // UI/UX 디자인 → 디자인
 //
 // badge 클래스를 이용하여 카테고리를 디자인합니다.
 // 슬라이드를 이동하면 카테고리도 함께 변경됩니다.


 // =====================================================
 // 16단계. 카드 제목과 설명 출력
 // =====================================================
 // content 영역에 현재 카드의 정보를 표시합니다.
 //
 // cards[currentIndex].title → 카드 제목
 // cards[currentIndex].desc → 카드 설명
 //
 // 예시
 // 제목: React 기초
 // 설명: 컴포넌트, props, state를 배우는 단계
 //
 // currentIndex가 변경되면 제목과 설명도 변경됩니다.
 //
 // 하나의 카드 UI를 유지하면서 데이터만 교체하는 구조입니다.


 // =====================================================
 // 17단계. 자세히 보기 버튼 구현
 // =====================================================
 // 카드 아래쪽에 "자세히 보기" 버튼을 표시합니다.
 //
 // 현재 예제에서는 버튼의 화면만 구현되어 있습니다.
 // onClick 이벤트나 페이지 이동 기능은 연결되지 않았습니다.
 //
 // 실제 프로젝트에서는 React Router 등을 이용해
 // 상세페이지로 이동하는 기능을 추가할 수 있습니다.


 // =====================================================
 // 18단계. 하단 페이지 표시 점 자동 생성
 // =====================================================
 // dots 영역은 카드의 개수와 현재 위치를 표시합니다.
 //
 // cards.map()을 이용하여 카드 개수만큼 점을 생성합니다.
 //
 // 카드가 6개이므로 점도 6개가 생성됩니다.
 //
 // 각 점에는 배열의 index를 key로 사용합니다.
 //
 // 예시
 // 첫 번째 점 → 첫 번째 카드
 // 두 번째 점 → 두 번째 카드
 // 세 번째 점 → 세 번째 카드
 //
 // 점을 클릭하면 해당 카드로 이동할 수 있습니다.


 // =====================================================
 // 19단계. 현재 페이지 표시 점 활성화
 // =====================================================
 // currentIndex와 점의 index를 비교합니다.
 //
 // 두 값이 같으면 active 클래스를 적용합니다.
 //
 // 예시
 // currentIndex = 0 → 첫 번째 점 활성화
 // currentIndex = 2 → 세 번째 점 활성화
 // currentIndex = 5 → 여섯 번째 점 활성화
 //
 // CSS에서 active 점의 색상이나 크기를 다르게 설정할 수 있습니다.
 //
 // 사용자는 현재 몇 번째 카드를 보고 있는지 확인할 수 있습니다.


 // =====================================================
 // 20단계. 페이지 표시 점 클릭 및 화면 업데이트
 // =====================================================
 // 사용자가 하단 점을 클릭하면 onClick 이벤트가 실행됩니다.
 //
 // setCurrentIndex(index)로 클릭한 점의 인덱스를 저장합니다.
 //
 // 실행 흐름
 // 하단 점 클릭
 // → setCurrentIndex(index) 실행
 // → currentIndex 상태 변경
 // → React 컴포넌트 재렌더링
 // → 선택한 카드 이미지 변경
 // → 카드 제목과 설명 변경
 // → 카테고리 배지 변경
 // → 선택한 점에 active 클래스 적용
 //
 // 이전·다음 버튼을 누르지 않아도 원하는 카드로 이동할 수 있습니다.


 // =====================================================
 // 최종 실행 결과
 // =====================================================
 // 1. 카드 데이터 6개를 준비합니다.
 // 2. 처음 실행하면 React 기초 카드를 표시합니다.
 // 3. 이전 버튼을 클릭하면 이전 카드로 이동합니다.
 // 4. 다음 버튼을 클릭하면 다음 카드로 이동합니다.
 // 5. 첫 번째 카드에서 이전을 누르면 마지막 카드로 이동합니다.
 // 6. 마지막 카드에서 다음을 누르면 첫 번째 카드로 이동합니다.
 // 7. 현재 카드의 이미지, 카테고리, 제목, 설명을 표시합니다.
 // 8. 카드 개수만큼 하단 페이지 표시 점을 생성합니다.
 // 9. 현재 선택된 점에 active 클래스를 적용합니다.
 // 10. 하단 점을 클릭하면 해당 카드로 바로 이동합니다.
 // 11. 슬라이드 이동 시 카드 내용이 자동으로 변경됩니다.
 // 12. 별도의 페이지 새로고침 없이 슬라이드가 작동합니다.


