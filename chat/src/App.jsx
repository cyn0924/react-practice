// React에서 화면을 만들기 위한 기본 기능과 상태 관리에 필요한 Hook들을 불러옵니다.
// useState는 컴포넌트의 변경되는 값을 저장합니다.
// useEffect는 컴포넌트가 화면에 표시되거나 상태가 변경될 때 특정 작업을 실행합니다.
// useMemo는 계산 결과를 기억해서 불필요한 재계산을 줄입니다.
// useRef는 DOM 요소나 값에 직접 접근할 때 사용합니다.
import React, { useEffect, useMemo, useRef, useState } from "react";
import "./App.css";

// 현재 시간을 "시:분" 형식의 문자열로 반환하는 함수입니다.
function getCurrentTime() {
  
  // 현재 날짜와 시간을 가져옵니다.
  const now = new Date();

  // 현재 시간을 가져오고, 한 자리 숫자라면 앞에 0을 붙입니다.
  // 예: 9시 -> "09"
  const hour = String(now.getHours()).padStart(2, "0");

  // 현재 분을 가져오고, 한 자리 숫자라면 앞에 0을 붙입니다.
  // 예: 5분 -> "05"
  const minute = String(now.getMinutes()).padStart(2, "0");

  // "시:분" 형태로 현재 시간을 반환합니다.
  return `${hour}:${minute}`;
}

// 채팅 앱 전체 화면을 담당하는 App 컴포넌트입니다.
function App() {

  // 채팅 메시지 목록을 저장하는 상태입니다.
  // 처음에는 봇이 보낸 안내 메시지 두 개를 미리 넣습니다.
  const [messages, setMessages] = useState([
    {

      // 메시지를 구분하기 위한 고유 번호입니다.
      id: 1,

      // 메시지를 보낸 사람이 봇임을 나타냅니다.
      sender: "bot",

      // 화면에 표시할 메시지 내용입니다.
      text: "안녕하세요! 실시간 UI 채팅 앱 예제입니다.",

      // 메시지가 작성된 시간을 저장합니다.
      time: getCurrentTime(),
    },
    {
      id: 2,
      sender: "bot",
      text: "메시지를 입력하면 자동 응답도 확인할 수 있어요.",
      time: getCurrentTime(),
    },
  ]);

  // 사용자가 입력창에 작성 중인 문장을 저장합니다.
  const [input, setInput] = useState("");

  // 봇이 답변을 준비하는 중인지 저장합니다.
  // true이면 입력 중 표시를 화면에 보여줍니다.
  const [isTyping, setIsTyping] = useState(false);

  // 상대방의 온라인 상태를 저장합니다.
  const [isOnline, setIsOnline] = useState(true);

  // 읽지 않은 메시지 개수를 저장합니다.
  const [unreadCount, setUnreadCount] = useState(0);

  // 채팅 내용 영역 DOM을 가리키는 ref입니다.
  // 앱이 시작되거나 채팅이 초기화될 때 입력창에 포커스를 줍니다.
  const chatBodyRef = useRef(null);

  // 메시지 입력 textarea DOM을 가리키는 ref입니다.
  // 앱이 시작되거나 채팅이 초기화될 때 입력창에 포커스를 줍니다.
  const inputRef = useRef(null);

  // 현재 실행 중인 자동 응답 타이머들을 set에 저장합니다.
  // 채팅 초기화나 컴포넌트 종료시 타이머를 모두 정리할 수 있습니다.
  const replyTimersRef = useRef(new Set());

  // 다음 메시지에 사용할 번호를 저장합니다.
  // useRef를 사용하므로 값이 바뀌어도 화면을 다시 렌더링하지 않습니다.
  const nextIdRef = useRef(3);

  // 사용자가 빠르게 선택할 수 있는 미리 작성된 답변 목록입니다.
  // useMemo를 사용해 컴포넌트가 다시 렌더링 되어도 배열을 다시 만들지 않습니다.
  const quickReplies = useMemo(
    () => [
      "안녕하세요",
      "오늘 일정 알려줘",
      "React 공부 중이에요",
      "도움이 필요해요",
    ],
    []
  );

  // 상대방의 온라인 상태를 일정한 시간마다 변경합니다.
  useEffect(() => {

    // 8초마다 온라인/오프라인 상태를 반대로 변경합니다.
    const onlineTimer = setInterval(() => {
      setIsOnline((prev) => !prev);
    }, 8000);

    // 컴포넌트가 사라질 때 반복 타이머를 정리합니다.
    return () => clearInterval(onlineTimer);
  }, []);

  // 컴포넌트가 처음 화면에 표시될 때 실행합니다.
  useEffect(() => {

    // 채팅 영역 DOM이 존재하는지 확인합니다.
    if (chatBodyRef.current) {

      // 스크롤 위치를 전체 높이로 설정해 가장 아래 메시지를 보여줍니다.
      chatBodyRef.current.scrollTop =
        chatBodyRef.current.scrollHeight;
    }
  }, [messages, isTyping]);

  useEffect(() => {

    // 입력창에 자동으로 포커스를 줍니다.
    inputRef.current?.focus();
  }, []);

  // 브라우저 탭이 보이는 상태가 바뀔 때 실행합니다.
  useEffect(() => {

    // 현재 문서가 다시 화면에 보이는지 확인하는 함수입니다.
    const handleVisibility = () => {

      // 탭이 다시 보이면 읽지 않은 알림 개수를 0으로 초기화합니다.
      if (!document.hidden) {
        setUnreadCount(0);
      }
    };

    // visibilitychange 이벤트를 등록합니다.
    document.addEventListener("visibilitychange", handleVisibility);

    // 컴포넌트가 사라질 때 이벤트를 제거합니다.
    return () => {
      document.removeEventListener(
        "visibilitychange",
        handleVisibility
      );
    };
  }, []);

  // 컴포넌트가 종료될 때 실행 중인 자동 응답 타이머를 정리합니다.
  useEffect(() => {

    // 현재 타이머 set을 변수에 저장합니다.
    const timers = replyTimersRef.current;

    // 컴포넌트가 제거될 때 모든 타이머를 취소합니다.
    return () => {
      timers.forEach((timer) => clearTimeout(timer));

      // 타이머 목록도 비워 메모리 누수를 방지합니다.
      timers.clear();
    };
  }, []);

  // 사용자의 메시지 내용에 따라 자동 답변을 반환하는 함수입니다.
  function getAutoReply(userText) {

    // 검색하기 쉽도록 입력 문장을 소문자로 변경합니다.
    const text = userText.toLowerCase();

    // "안녕" 이라는 단어가 포함되어 있으면 인사 답변을 반환합니다.
    if (text.includes("안녕")) {
      return "안녕하세요! 만나서 반가워요 😊";
    }

    // "리액트" 또는 "react"가 포함되어 있으면 React 관련 답변을 반환합니다.
    if (text.includes("리액트") || text.includes("react")) {
      return "React에서는 state와 props 흐름을 이해하는 것이 정말 중요해요.";
    }

    // "공부"라는 단어가 포함되어 있으면 공부 관련 답변을 반환합니다.
    if (text.includes("공부")) {
      return "작게 자주 만드는 연습이 실력 향상에 가장 좋아요.";
    }

    if (text.includes("도움")) {
      return "물론이죠! 어떤 부분이 궁금한지 알려주세요.";
    }

    if (text.includes("일정")) {
      return "오늘 일정은 아직 등록되지 않았어요. 새 일정을 추가해보세요.";
    }

    // 위 조건에 해당하지 않으면 기본 답변을 반환합니다.
    return "좋아요! 방금 보낸 메시지를 잘 받았어요.";
  }

  // 사용자의 메시지를 채팅 목록에 추가하고 자동 응답을 예약하는 함수입니다.
  // customText가 전달되면 해당 문장을 사용하고
  // 전달되지 않으면 입력창의 내용을 사용합니다. 
  function sendMessage(customText) {

    // 입력값의 앞뒤 공백을 제거합니다.
    const text = (customText ?? input).trim();

    // 입력값이 비어 있으면 아무 작업도 하지 않습니다.
    if (!text) return;

    // 사용자가 보낸 메시지 객체를 만듭니다.
    const userMessage = {

      // 현재 번호를 사용한 뒤 다음 번호를 1 증가시킵니다.
      id: nextIdRef.current++,

      // 사용자가 보낸 메시지임을 표시합니다.
      sender: "me",

      // 입력한 내용
      text,

      // 메시지를 보낸 현재 시간을 저장합니다.
      time: getCurrentTime(),
    };

    // 기존 메시지 뒤에 사용자의 메시지를 추가합니다.
    setMessages((prev) => [...prev, userMessage]);

    // 메시지를 보낸 후 입력창을 비웁니다.
    setInput("");

    // 봇이 답변을 작성 중인 상태로 변경합니다.
    setIsTyping(true);

    // 1.2초 후 자동 답변을 실행하는 타이머를 만듭니다.
    const timer = setTimeout(() => {

      // 실행이 끝난 타이머를 set에서 제거합니다.
      replyTimersRef.current.delete(timer);

      // 봇이 보낼 답변 객체를 만듭니다.
      const botMessage = {

        // 다음 메시지 번호를 사용합니다.
        id: nextIdRef.current++,

        // 봇이 보낸 메시지임을 표시합니다.
        sender: "bot",

        // 사용자 문장에 맞는 자동 답변을 생성합니다.
        text: getAutoReply(text),

        // 자동 답변이 생성된 시간을 저장합니다.
        time: getCurrentTime(),
      };

      // 기존 메시지 목록 뒤에 봇 답변을 추가합니다.
      setMessages((prev) => [...prev, botMessage]);

      // 브라우저 탭이 보이지 않는 상태라면 읽지 않은 알림 수를 증가시킵니다.
      if (document.hidden) {
        setUnreadCount((prev) => prev + 1);
      }

      // 아직 실행중인 답변 타이머가 있으면 계속 입력 중으로 표시됩니다.
      setIsTyping(replyTimersRef.current.size > 0);
    }, 1200);

    // 생성한 타이머를 set에 저장합니다.
    replyTimersRef.current.add(timer);
  }

  // 현재 채팅 내용을 모두 지우는 함수입니다.
  function resetChat() {

    // 아직 실행되지 않은 자동 응답 타이머를 모두 취소합니다.
    replyTimersRef.current.forEach((timer) => clearTimeout(timer));

    // 타이머 목록을 비웁니다
    replyTimersRef.current.clear();

    // 메시지 목록을 빈 배열로 초기화합니다.
    setMessages([]);

    // 입력창 내용을 초기화합니다.
    setInput("");

    // 입력중 표시를 숨깁니다.
    setIsTyping(false);

    // 읽지 않은 알림 수를 초기화합니다.
    setUnreadCount(0);

    // 채팅 초기화 후 입력창에 다시 포커스를 줍니다.
    inputRef.current?.focus();
  }

  // form이 제출될 때 실행되는 함수입니다.
  function handleSubmit(e) {

    // form의 기본 새로 고침 동작을 막습니다.
    e.preventDefault();

    // 입력창의 메시지를 전송합니다.
    sendMessage();
  }

  // textarea에서 키보드를 눌렀을 때 실행되는 함수입니다.
  function handleKeyDown(e) {

    // 한글 입력 조합 중에는 Enter 키가 전송으로 처리되지 않도록 처리합니다.
    if (e.nativeEvent.isComposing) return;

    // shift 없이 Enter를 누르면 메시지를 전송합니다.
    if (e.key === "Enter" && !e.shiftKey) {

      // textarea의 줄바꿈 기본 동작을 막습니다.
      e.preventDefault();

      // 메시지를 전송합니다.
      sendMessage();
    }
  }

  // 화면에 실제 채팅 앱 UI를 반환합니다.
  return (
    <div className="chat-page">

      {/* 사이드바와 채팅 영역을 함께 감싸는 앱 컨테이너입니다. */}
      <div className="chat-app">

        {/* 사용자 정보와 상태, 빠른 답장을 보여주는 사이드바입니다. */}
        <aside className="chat-sidebar">

          {/* 채팅방 프로필 정보를 보여주는 카드입니다. */}
          <div className="profile-card">

            {/* 채팅방 대표글자를 표시하는 아바타입니다. */}
            <div className="avatar-large">C</div>

            {/* 채팅방 이름과 설명 표시합니다. */}
            <div>
              <h2 className="sidebar-title">Chat Room</h2>
              <p className="sidebar-text">실시간 채팅 UI 예제</p>
            </div>
          </div>

          {/* 상대방 상태와 읽지 않은 알림 수를 보여주는 카드입니다. */}
          <div className="status-card">

            {/* 온라인 상태를 한줄로 보여줍니다. */}
            <div className="status-row">

              {/* 온라인 여부에 따라 online 또는 offline 클래스를 적용합니다. */}
              <span
                className={`status-dot ${
                  isOnline ? "online" : "offline"
                }`}
              />

              {/* 온라인 상태에 따라 안내 문구를 변경합니다.ㅓ */}
              <span className="status-text">
                {isOnline ? "상대방 온라인" : "상대방 오프라인"}
              </span>
            </div>

            {/* 읽지 않은 알림 개수를 보여주는 영역입니다. */}
            <div className="unread-box">
              <span className="unread-label">읽지 않은 알림</span>

              {/* 현재 읽지 않은 메시지 개수를 표시합니다. */}
              <strong className="unread-count">
                {unreadCount}
              </strong>
            </div>
          </div>

          {/* 미리 작성된 메시지를 보여주는 빠른 답장 카드입니다. */}
          <div className="quick-reply-card">
            <h3 className="quick-reply-title">빠른 답장</h3>

            <div className="quick-reply-list">
              {quickReplies.map((reply) => (

                // 각각의 빠른 답장 문장을 버튼으로 표시합니다.
                <button
                  key={reply}
                  type="button"
                  className="quick-reply-button"
                  onClick={() => sendMessage(reply)}
                >
                  {reply}
                </button>
              ))}
            </div>
          </div>
        </aside>

        {/* 채팅 헤더, 메시지 목록, 입력창을 포함하는 메인 영역입니다. */}
        <main className="chat-section">

          {/* 채팅방 제목과 초기화 버튼을 보여주는 헤더입니다. */}
          <header className="chat-header">

            {/* 상대방 아바타와 상태 문구를 묶는 영역입니다. */}
            <div className="chat-header-left">

              {/* 상대방을 나타내는 아바타입니다. */}
              <div className="chat-avatar">B</div>

              {/* 채팅 제목과 온라인 상태 설명입니다. */}
              <div>
                <h1 className="chat-title">실시간 채팅 앱</h1>

                <p className="chat-subtitle">
                  {isOnline
                    ? "지금 바로 응답 가능"
                    : "잠시 자리를 비웠어요"}
                </p>
              </div>
            </div>

            {/* 현재 채팅을 모두 초기화하는 함수입니다. */}
            <button
              type="button"
              className="header-button"
              onClick={resetChat}
            >
              채팅 초기화
            </button>
          </header>

          {/* 메시지 목록이 표시되는 영역입니다. */}
          <div ref={chatBodyRef} className="chat-body">

            {/* 메시지가 하나도 없을 때 빈 상태 화면을 보여줍니다. */}
            {messages.length === 0 ? (
              <div className="empty-state">
                <div className="empty-icon">💬</div>
                <p className="empty-text">
                  아직 메시지가 없습니다.
                </p>
              </div>
            ) : (

              // 메시지가 있으면 message 배열을 반복해서 화면에 표시합니다.
              messages.map((message) => {

                // Sender 값이 "me"이면 사용자가 보낸 메시지입니다.
                const isMe = message.sender === "me";

                return (

                  // 메시지 하나를 감싸는 행입니다.
                  <div
                    key={message.id}
                    className={`message-row ${
                      isMe ? "is-me" : "is-bot"
                    }`}
                  >

                    {/* 봇 메시지일 때만 왼쪽에 아바타를 표시합니다. */}
                    {!isMe && (
                      <div className="message-avatar">B</div>
                    )}

                    {/* 사용자 메시지와 봇 메시지에 따라 다른 스타일을 적용합니다. */}
                    <div
                      className={`message-bubble ${
                        isMe ? "my-message" : "bot-message"
                      }`}
                    >
                      <p className="message-text">
                        {message.text}
                      </p>

                      <span className="message-time">
                        {message.time}
                      </span>
                    </div>
                  </div>
                );
              })
            )}

            {/* 봇이 답변을 준비 중이면 입력 중 말풍선을 표시합니다. */}
            {isTyping && (
              <div className="message-row is-bot">

                {/* 봇 아바타를 표시합니다. */}
                <div className="message-avatar">B</div>

                {/* 접근성용 설명을 포함한 입력 중 표시 영역입니다. */}
                <div
                  className="typing-bubble"
                  role="status"
                  aria-label="상대방이 입력 중입니다."
                >

                  {/* 움직이는 점 세개를 표시합니다. */}
                  <span className="typing-dot" />
                  <span className="typing-dot" />
                  <span className="typing-dot" />
                </div>
              </div>
            )}
          </div>

          {/* 메시지를 입력하고 전송하는 form 영역입니다. */}
          <form className="input-area" onSubmit={handleSubmit}>

            {/* 여러 줄의 메시지를 입력할 수 있는 textarea입니다. */}
            <textarea
              ref={inputRef}
              className="chat-textarea"
              placeholder="메시지를 입력하세요..."
              aria-label="메시지 입력"
              value={input}
              onChange={(e) => setInput(e.target.value)}
              onKeyDown={handleKeyDown}
              rows={2}
            />

            {/* 입력값이 있을 때만 활성화되는 전송 버튼입니다. */}
            <button
              className="send-button"
              type="submit"
              disabled={!input.trim()}
            >
              전송
            </button>
          </form>
        </main>
      </div>
    </div>
  );
}

