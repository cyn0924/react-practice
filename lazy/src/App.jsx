// 여기서는 학습을 위해 Promise.resolve로 컴포넌트를 즉시 반환합니다.
const HomePage = lazy(() =>

  // lazy는 반드시 컴포넌트가 포함된 Promise를 반환해야 합니다.
  Promise.resolve({

    // Promise안의 default 속성에 실제 컴포넌트를 넣습니다.
    default: function HomePage() {

      // 홈페이지 화면을 반환합니다.
      return (

        // 홈페이지 전체 영역입니다.
        <div className="page-box">

          {/* 홈 페이지 제목 */}
          <h2 className="page-title">홈 페이지</h2>

          {/* 홈 페이지 설명 문구 */}
          <p className="page-text">
            이 영역은 lazy loading으로 필요할 때만 불러오는 컴포넌트입니다.
          </p>

          {/* 홈 페이지의 설명 카드를 배치하는 영역입니다. */}
          <div className="card-grid">

            {/* 첫 번째 설명 카드 */}
            <div className="info-card">

              {/* 카드 제목 */}
              <h3 className="card-title">빠른 초기 렌더링</h3>

              {/* 카드 설명 */}
              <p className="card-text">
                처음부터 모든 컴포넌트를 다 불러오지 않고, 필요한 순간에만 로드할
                수 있습니다.
              </p>
            </div>

            {/* 두 번째 설명 카드 */}
            <div className="info-card">
              <h3 className="card-title">코드 분할</h3>
              <p className="card-text">
                큰 프로젝트에서 페이지 단위, 기능 단위로 나눠서 관리하기 좋습니다.
              </p>
            </div>
          </div>
        </div>
      );
    },
  })
);

