// React 라이브러리와 상태 관리를 위한 useState Hook을 불러옵니다.
// useState는 현재 어떤 탭이 선택되어 있는지 저장하고 변경할 때 사용합니다.
// useState는 현재 열려 있는 아코디언 항목 id처럼 바뀌는 값을 저장할 때 사용합니다.
import React, { useState } from "react";
import "./App.css";

// 아코디언 UI 전체를 담당하는 App 컴포넌트를 선언합니다.
function App() {

  // 현재 열려 있는 아코디언 항목의 id를 저장하는 상태입니다. 
  // 처음에는 아무 항목도 열려있지 않으므로 null로 시작합니다.
  const [openId, setOpenId] = useState(null);

  // 아코디언 표시할 질문과 답변 데이터를 배열로 선언합니다.
  // 각 항목은 id, title, content 값을 가진 객체입니다.
  const accordionItems = [

    // 첫 번째 아코디언 항목입니다.
    {
      id: 1,
      title: "React란 무엇인가요?",
      content:
        "React는 사용자 인터페이스를 만들기 위한 JavaScript 라이브러리입니다.",
    },
    {
      id: 2,
      title: "아코디언 UI는 어디에 사용하나요?",
      content: "FAQ, 설정 메뉴 등에서 자주 사용됩니다.",
    },
    {
      id: 3,
      title: "핵심 포인트는 무엇인가요?",
      content: "state와 조건부 렌더링입니다.",
    },
    {
      id: 4,
      title: "여러 개 열 수 있나요?",
      content: "state를 배열로 바꾸면 가능합니다.",
    },
  ];

  // 특정 아코디언 항목을 열거나 닫는 함수를 선언합니다.
  const toggleAccordion = (id) => {

    // 이전에 열려 이썬 항목 id를 기준으로 새 상태를 계산합니다.
    setOpenId((prev) => 
      
      // 이미 같은 항목이 열려 있으면 null로 바꿔닫고
      // 다른 항목이거나 아무것도 열려 있지 않으면 해당 id를 저장해 엽니다.
      (prev === id ? null : id));
  };

  // 화면에 렌더링할 JSX 구조를 반환합니다.
  return (

    // 전체 아코디언 화면의 최상위 컨테이너입니다.
    <div className="container">
      <h1 className="title">아코디언 UI</h1>

      <p className="description">
        클릭하면 열리고 다시 클릭하면 닫힙니다.
      </p>

      {/* 아코디언 카드 전체를 감싸는 영역입니다. */}
      <div className="accordionWrap">

        {/* 배열을 순회하면서 각 질문/답변 카드 하나씩 출력합니다. */}
        {accordionItems.map((item) => (

          // 각 아코디언 항목 카드입니다.
          <div key={item.id} className="card">

            {/* 질문 제목을 클릭할 수 있는 버튼입니다. */}
            <button

              // 버튼 클릭 시 현재 항목 id를 넘겨 toggleAccodion 함수를 실행합니다.
              onClick={() => toggleAccordion(item.id)}
              className="questionButton"
            >
              
              {/* 질문 제목 텍스트를 표시합니다. */}
              <span className="questionText">{item.title}</span>

              {/* 현재 항목이 열려 있는지 닫혀 있는지에 따라 아이콘을 다르게 표시합니다. */}
              <span className="icon">
                {openId === item.id ? "−" : "+"}
              </span>
            </button>

            {/* 현재 openId와 item.id가 같을 때만 답변 영역을 렌더링합니다. */}
            {openId === item.id && (

              // 답변 내용을 감싸는 영역입니다.
              <div className="answerBox">

                {/* 실제 답변 텍스트를 표시합니다. */}
                <p className="answerText">{item.content}</p>
              </div>
            )}
          </div>
        ))}
      </div>
    </div>
  );
}

export default App;


 // =====================================================
 // React 아코디언 UI 전체 실행 흐름
 // =====================================================
 // 1. React와 useState를 불러옵니다.
 // 2. 현재 열려 있는 아코디언 항목을 관리합니다.
 // 3. 질문과 답변으로 구성된 아코디언 데이터를 준비합니다.
 // 4. 사용자가 질문 버튼을 클릭합니다.
 // 5. 클릭한 질문의 ID를 확인합니다.
 // 6. 기존에 열려 있는 질문과 비교합니다.
 // 7. 같은 질문이면 답변을 닫습니다.
 // 8. 다른 질문이면 기존 답변을 닫고 새 답변을 엽니다.
 // 9. 선택된 질문의 아이콘을 +에서 −로 변경합니다.
 // 10. 선택된 질문의 답변 내용을 화면에 표시합니다.
 // 11. React 상태 변경에 따라 화면이 자동 업데이트됩니다.
 // =====================================================


 // =====================================================
 // 1단계. React 기능 및 CSS 불러오기
 // =====================================================
 // React는 컴포넌트를 만들기 위해 사용합니다.
 // useState는 현재 열려 있는 아코디언 항목을 관리합니다.
 // App.css는 아코디언 버튼과 답변 영역의 디자인을 담당합니다.


 // =====================================================
 // 2단계. App 컴포넌트 생성
 // =====================================================
 // App은 전체 아코디언 UI를 관리하는 컴포넌트입니다.
 //
 // 주요 역할
 // 아코디언 데이터 관리
 // 현재 열린 질문 관리
 // 질문 버튼 클릭 처리
 // 답변 열기 및 닫기
 // 아이콘 변경
 // 질문과 답변 화면 출력
 //
 // 하나의 상태로 여러 질문의 열림 여부를 관리합니다.


 // =====================================================
 // 3단계. 아코디언 열림 상태 관리
 // =====================================================
 // openId는 현재 열려 있는 아코디언의 ID를 저장합니다.
 //
 // useState(null)로 초기값을 설정합니다.
 //
 // null이면 모든 아코디언이 닫혀 있습니다.
 //
 // 예시
 // openId = null → 모든 질문 닫힘
 // openId = 1 → 첫 번째 질문 열림
 // openId = 2 → 두 번째 질문 열림
 // openId = 3 → 세 번째 질문 열림
 //
 // 한 번에 하나의 질문만 열리도록 관리합니다.


 // =====================================================
 // 4단계. 아코디언 데이터 배열 준비
 // =====================================================
 // accordionItems 배열에 질문과 답변을 저장합니다.
 //
 // 각 항목에는 다음 정보가 있습니다.
 //
 // id      → 질문 고유번호
 // title   → 질문 제목
 // content → 질문에 대한 답변
 //
 // 총 4개의 질문과 답변을 준비합니다.
 //
 // 배열로 관리하므로 질문이 추가되어도
 // 동일한 UI 구조로 반복 출력할 수 있습니다.


 // =====================================================
 // 5단계. 첫 번째 질문 데이터 설정
 // =====================================================
 // 첫 번째 질문은 React에 대한 설명입니다.
 //
 // 질문: React란 무엇인가요?
 //
 // 답변
 // React는 사용자 인터페이스를 만들기 위한
 // JavaScript 라이브러리입니다.
 //
 // 첫 번째 질문을 클릭하면 이 답변이 표시됩니다.


 // =====================================================
 // 6단계. 두 번째 질문 데이터 설정
 // =====================================================
 // 두 번째 질문은 아코디언 UI의 활용 분야입니다.
 //
 // 질문: 아코디언 UI는 어디에 사용하나요?
 //
 // 답변
 // FAQ, 설정 메뉴 등에서 자주 사용됩니다.
 //
 // 아코디언은 많은 정보를 필요한 경우에만
 // 펼쳐 볼 수 있도록 구성하는 UI입니다.


 // =====================================================
 // 7단계. 세 번째 질문 데이터 설정
 // =====================================================
 // 세 번째 질문은 아코디언 구현의 핵심 개념입니다.
 //
 // 질문: 핵심 포인트는 무엇인가요?
 //
 // 답변
 // state와 조건부 렌더링입니다.
 //
 // React의 상태를 이용하여
 // 답변을 표시할지 결정하는 구조입니다.


 // =====================================================
 // 8단계. 네 번째 질문 데이터 설정
 // =====================================================
 // 네 번째 질문은 여러 항목을 동시에 열 수 있는지에 대한 내용입니다.
 //
 // 질문: 여러 개 열 수 있나요?
 //
 // 답변
 // state를 배열로 바꾸면 가능합니다.
 //
 // 현재 예제에서는 openId에 하나의 ID만 저장합니다.
 // 따라서 한 번에 하나의 질문만 열 수 있습니다.
 //
 // 여러 항목을 동시에 열려면
 // 열린 ID들을 배열이나 Set으로 관리할 수 있습니다.


 // =====================================================
 // 9단계. 아코디언 열기 및 닫기 함수
 // =====================================================
 // toggleAccordion 함수는 질문을 클릭하면 실행됩니다.
 //
 // 클릭한 질문의 id를 전달받습니다.
 //
 // 실행 흐름
 // 질문 버튼 클릭
 // → toggleAccordion(id) 실행
 // → 현재 openId와 클릭한 id 비교
 // → 열기 또는 닫기 결정
 // → setOpenId 실행
 // → React 화면 자동 업데이트


 // =====================================================
 // 10단계. 같은 질문을 다시 클릭했을 때 처리
 // =====================================================
 // 현재 openId와 클릭한 질문의 id가 같으면
 // openId를 null로 변경합니다.
 //
 // 예시
 // 첫 번째 질문 클릭 → openId = 1
 // 첫 번째 질문 다시 클릭 → openId = null
 //
 // 따라서 열려 있는 질문을 다시 클릭하면
 // 해당 답변이 닫힙니다.


 // =====================================================
 // 11단계. 다른 질문을 클릭했을 때 처리
 // =====================================================
 // 현재 openId와 클릭한 질문의 id가 다르면
 // 새로 클릭한 질문의 id를 openId에 저장합니다.
 //
 // 예시
 // 첫 번째 질문이 열린 상태 → openId = 1
 // 세 번째 질문 클릭 → openId = 3
 //
 // 첫 번째 질문의 답변은 자동으로 닫힙니다.
 // 세 번째 질문의 답변이 새롭게 열립니다.
 //
 // openId에는 하나의 ID만 저장되므로
 // 여러 답변이 동시에 열리지 않습니다.


 // =====================================================
 // 12단계. JSX 전체 화면 구성
 // =====================================================
 // return에서 사용자가 보는 아코디언 화면을 만듭니다.
 //
 // 화면 구성
 // 1. 아코디언 UI 제목
 // 2. 아코디언 사용 방법 설명
 // 3. 질문과 답변을 표시하는 영역
 // 4. 질문 버튼
 // 5. 열림 및 닫힘 아이콘
 // 6. 선택된 질문의 답변
 //
 // openId 상태에 따라 화면이 자동 변경됩니다.


 // =====================================================
 // 13단계. 아코디언 제목과 설명 출력
 // =====================================================
 // 화면 상단에 "아코디언 UI" 제목을 표시합니다.
 //
 // 설명 문구
 // 클릭하면 열리고 다시 클릭하면 닫힙니다.
 //
 // 사용자가 아코디언 사용 방법을 쉽게 이해하도록 안내합니다.


 // =====================================================
 // 14단계. 아코디언 항목 반복 출력
 // =====================================================
 // accordionItems 배열을 map으로 반복합니다.
 //
 // 배열에 저장된 질문 하나마다 카드 하나를 생성합니다.
 //
 // 각 카드에는 다음 요소가 있습니다.
 // 질문 버튼
 // 질문 제목
 // 열림 및 닫힘 아이콘
 // 답변 내용
 //
 // key에는 각 질문의 고유번호인 item.id를 사용합니다.
 //
 // 질문 개수가 늘어나도 map으로 자동 생성할 수 있습니다.


 // =====================================================
 // 15단계. 질문 버튼 클릭 이벤트 처리
 // =====================================================
 // questionButton은 아코디언을 열고 닫는 버튼입니다.
 //
 // 사용자가 버튼을 클릭하면 onClick 이벤트가 발생합니다.
 //
 // onClick에서 toggleAccordion(item.id)를 실행합니다.
 //
 // 클릭한 질문의 ID가 함수로 전달됩니다.
 //
 // 질문의 열림 상태를 변경하고
 // 해당 질문의 답변 표시 여부를 결정합니다.


 // =====================================================
 // 16단계. 질문 제목 출력
 // =====================================================
 // item.title을 이용하여 질문 제목을 표시합니다.
 //
 // 예시
 // React란 무엇인가요?
 // 아코디언 UI는 어디에 사용하나요?
 // 핵심 포인트는 무엇인가요?
 // 여러 개 열 수 있나요?
 //
 // 질문 제목은 questionText 클래스를 이용하여 디자인합니다.


 // =====================================================
 // 17단계. 열림 및 닫힘 아이콘 변경
 // =====================================================
 // openId와 item.id를 비교하여 아이콘을 결정합니다.
 //
 // 두 값이 같으면 − 아이콘을 표시합니다.
 // 두 값이 다르면 + 아이콘을 표시합니다.
 //
 // + → 답변이 닫혀 있는 상태
 // − → 답변이 열려 있는 상태
 //
 // 삼항 연산자를 사용하여 아이콘을 변경합니다.
 //
 // 질문을 클릭할 때마다 상태에 맞게 아이콘이 변경됩니다.


 // =====================================================
 // 18단계. 답변 영역 조건부 렌더링
 // =====================================================
 // openId === item.id 조건을 확인합니다.
 //
 // 현재 열린 질문과 해당 항목의 ID가 같으면
 // answerBox 영역을 화면에 표시합니다.
 //
 // 두 값이 다르면 답변 영역을 표시하지 않습니다.
 //
 // 조건부 렌더링에 && 연산자를 사용합니다.
 //
 // 선택된 질문의 답변만 화면에 나타납니다.


 // =====================================================
 // 19단계. 답변 내용 출력
 // =====================================================
 // item.content를 이용하여 답변 내용을 표시합니다.
 //
 // 답변이 열린 상태에서는
 // answerBox 안에 answerText가 표시됩니다.
 //
 // 질문을 닫으면 답변 영역이 렌더링되지 않습니다.
 //
 // 따라서 같은 카드에서 질문과 답변을
 // 자연스럽게 펼치고 접을 수 있습니다.


 // =====================================================
 // 20단계. React 상태 변경과 화면 자동 업데이트
 // =====================================================
 // 사용자가 첫 번째 질문을 클릭했다고 가정합니다.
 //
 // 첫 번째 질문 클릭
 // → onClick 이벤트 발생
 // → toggleAccordion(1) 실행
 // → setOpenId로 상태 변경
 // → openId가 1로 변경
 // → React가 App 컴포넌트 재렌더링
 // → 첫 번째 질문의 아이콘이 −로 변경
 // → 첫 번째 질문의 답변 표시
 //
 // 사용자가 두 번째 질문을 클릭하면
 // → toggleAccordion(2) 실행
 // → openId가 2로 변경
 // → 첫 번째 답변 닫힘
 // → 두 번째 답변 열림
 //
 // 별도의 페이지 이동 없이 답변 영역만 변경됩니다.


 // =====================================================
 // 최종 실행 결과
 // =====================================================
 // 1. 질문과 답변으로 구성된 아코디언 4개를 표시합니다.
 // 2. 처음에는 모든 질문이 닫혀 있습니다.
 // 3. 질문을 클릭하면 해당 답변이 열립니다.
 // 4. 같은 질문을 다시 클릭하면 답변이 닫힙니다.
 // 5. 다른 질문을 클릭하면 기존 답변은 닫힙니다.
 // 6. 한 번에 하나의 답변만 열 수 있습니다.
 // 7. 답변이 닫혀 있으면 + 아이콘을 표시합니다.
