// 가장 중요한 React 코드 스플리팅 작동 원리
// =====================================================
// 실제 프로젝트에서 페이지 컴포넌트를 별도 파일로 작성
// → React.lazy와 import()로 컴포넌트 정의
// → App에서 현재 페이지 상태 관리
// → 사용자가 메뉴 클릭
// → activePage 상태 변경
// → renderPage에서 필요한 페이지 선택
// → 처음 필요한 코드 청크가 아직 없다면 로드
// → 로딩 중에는 Suspense fallback 화면 표시
// → 코드 로딩 완료
// → 실제 페이지 컴포넌트 렌더링
// → 해당 페이지 화면 출력
//
// 핵심: 코드 스플리팅은 JavaScript 파일을 나누는 기술이고,
// Lazy Loading은 필요한 시점에 코드를 불러오는 방식입니다.
//
// React.lazy는 컴포넌트의 지연 로딩을 정의하고,
// Suspense는 준비 중에 표시할 UI를 담당합니다.
//
// 주의: 현재 예제는 Promise.resolve를 사용하므로
// 실제 JavaScript 파일이 분리되는 것은 아닙니다.
//
// 실제 코드 스플리팅을 적용하려면
// 각 컴포넌트를 별도 파일로 분리하고
// lazy(() => import("./pages/파일명"))을 사용해야 합니다.
// =====================================================
